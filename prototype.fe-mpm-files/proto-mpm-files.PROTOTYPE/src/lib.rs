pub struct Scope {
    pub dir: PathBuf,
}

impl Scope {
    pub fn repo(dir: &Path) -> Scope {
        Scope { dir: dir.to_path_buf() }
    }
    /// Machine scope: $HOME/.config/monochromatic-dev/toolchain (HOME is injected, never hard-coded).
    pub fn global() -> Result<Scope, String> {
        let home = std::env::var("HOME").map_err(|_| "HOME is not set".to_string())?;
        Ok(Scope { dir: PathBuf::from(home).join(".config/monochromatic-dev/toolchain") })
    }
    pub fn plan(&self) -> PathBuf {
        self.dir.join("toolchain.plan.jsonc")
    }
    pub fn lock(&self) -> PathBuf {
        self.dir.join("toolchain.lock.json")
    }
    pub fn packages(&self) -> PathBuf {
        self.dir.join("mpm.packages.toml")
    }
    pub fn managers(&self) -> PathBuf {
        self.dir.join("mpm.managers.toml")
    }
}

