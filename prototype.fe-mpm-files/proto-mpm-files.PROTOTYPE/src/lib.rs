/// Returns drift lines; an empty vec is a clean tree.
pub fn check_lock_vs_plan(scope: &Scope) -> Vec<String> {
    let mut drift = Vec::new();
    let plan = match read_json(&scope.plan()) {
        Ok(p) => p,
        Err(e) => return vec![format!("DRIFT plan: {e}")],
    };
    let Some(disk_text) = std::fs::read_to_string(scope.lock()).ok() else {
        return vec!["DRIFT toolchain.lock.json: missing".into()];
    };
    let disk: Value = match serde_json::from_str(&disk_text) {
        Ok(v) => v,
        Err(e) => return vec![format!("DRIFT toolchain.lock.json: not JSON ({e})")],
    };
    match project(&plan, Some(&disk), &BTreeMap::new()) {
        Ok(expected) => {
            if lock_text(&expected) != disk_text {
                drift.push("DRIFT toolchain.lock.json: differs from the plan projection".to_string());
            }
        }
        Err(e) => drift.push(format!("DRIFT toolchain.lock.json: {e}")),
    }
    drift
}

pub fn check_mpm_files(scope: &Scope, header: &str) -> Vec<String> {
    use std::os::unix::fs::PermissionsExt;
    let mut drift = Vec::new();
    let Some(disk) = std::fs::read_to_string(scope.lock()).ok().and_then(|t| serde_json::from_str::<Value>(&t).ok()) else {
        return vec!["DRIFT mpm files: lock unreadable, cannot render".into()];
    };
    for (path, want, mode) in [
        (scope.packages(), render::render_packages(&disk, header), 0o644u32),
        (scope.managers(), render::render_managers(&disk, header), 0o600u32),
    ] {
        let name = path.file_name().unwrap().to_string_lossy().to_string();
        match std::fs::read_to_string(&path) {
            Err(_) => drift.push(format!("DRIFT {name}: missing")),
            Ok(got) => {
                if got != want {
                    drift.push(format!("DRIFT {name}: differs from the render of the lock"));
                }
                let actual = std::fs::metadata(&path).map(|m| m.permissions().mode() & 0o777).unwrap_or(0);
                if actual != mode {
                    drift.push(format!("DRIFT {name}: mode {actual:o}, expected {mode:o}"));
                }
            }
        }
    }
    drift
}

