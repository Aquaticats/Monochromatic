pub fn parse_jsonc(text: &str) -> Result<Value, String> {
    let stripped: Vec<&str> = text.lines().filter(|l| !l.trim_start().starts_with("//")).collect();
    serde_json::from_str(&stripped.join("\n")).map_err(|e| format!("plan is not JSON after dropping full-line comments: {e}"))
}

pub fn read_json(path: &Path) -> Result<Value, String> {
    let text = std::fs::read_to_string(path).map_err(|e| format!("read {}: {e}", path.display()))?;
    parse_jsonc(&text)
}

fn put(map: &mut Map<String, Value>, key: &str, value: Option<&Value>) {
    if let Some(v) = value {
        map.insert(key.to_string(), v.clone());
    }
}

/// Plan fields into the lock, keeping resolved facts (version, artifacts) from the previous lock.
/// `resolutions` stands in for the network step of `mpm-shadow update`.
pub fn project(plan: &Value, old: Option<&Value>, resolutions: &BTreeMap<String, String>) -> Result<Value, String> {
    let plan_tools = plan.get("tools").and_then(Value::as_object).ok_or("plan has no tools object")?;
    let mut tools = Map::new();
    for (id, p) in plan_tools {
        let old_entry = old.and_then(|o| o.pointer(&format!("/tools/{}", id.replace('~', "~0").replace('/', "~1"))));
        let request = p.get("request").cloned().unwrap_or_else(|| json!({"track": "latest"}));
        let route = p.get("route").and_then(Value::as_str).ok_or(format!("{id}: no route"))?;
        let pinned = request.get("pinned").and_then(Value::as_str);
        let version: String = match (pinned, resolutions.get(id), old_entry.and_then(|e| e.get("version")).and_then(Value::as_str)) {
            (Some(pin), None, _) => pin.to_string(),
            (Some(_), Some(_), _) => return Err(format!("{id}: pinned in the plan, nothing to resolve")),
            (None, Some(r), _) => r.clone(),
            (None, None, Some(old_version)) => old_version.to_string(),
            (None, None, None) => return Err(format!("{id}: no version known offline; run `update`")),
        };
        let mut e = Map::new();
        e.insert("request".into(), request);
        e.insert("version".into(), Value::String(version.clone()));
        e.insert("route".into(), Value::String(route.to_string()));
        put(&mut e, "manager", p.get("manager"));
        if route == "rustup-toolchain" {
            e.insert("packageId".into(), Value::String(version.clone()));
        } else {
            put(&mut e, "packageId", p.get("packageId"));
        }
        put(&mut e, "bins", p.get("bins"));
        put(&mut e, "os", p.get("os"));
        e.insert("env".into(), p.get("env").cloned().unwrap_or_else(|| json!({})));
        e.insert("options".into(), p.get("options").cloned().unwrap_or_else(|| json!({})));
        if let Some(old_entry) = old_entry {
            if old_entry.get("version").and_then(Value::as_str) == Some(version.as_str()) {
                put(&mut e, "artifacts", old_entry.get("artifacts"));
            }
        }
        tools.insert(id.clone(), Value::Object(e));
    }
    Ok(json!({"schemaVersion": 1, "generatedFrom": "toolchain.plan.jsonc", "tools": Value::Object(tools)}))
}

pub fn lock_text(lock: &Value) -> String {
    let mut text = serde_json::to_string_pretty(lock).expect("lock serializes");
    text.push('\n');
    text
}

