pub fn run(args: &[&str]) -> i32 {
    eprintln!("$ {}", args.join(" "));
    match Command::new(args[0]).args(&args[1..]).status() {
        Ok(s) => s.code().unwrap_or(1),
        Err(e) => {
            eprintln!("spawn {}: {e}", args[0]);
            127
        }
    }
}

/// Installs every lock entry the prototype knows by running the owner tool directly, like providers.*.ts do.
/// The one exception is the rustup toolchain: candidates that keep the mpm files install it through
/// `mpm --rustup restore <mpm.packages.toml>` (the only code path in the repo today), with the direct rustup call
/// as the fallback when that fails, unless `fallback` is false.
pub fn sync(scope: &Scope, cand: Candidate, fallback: bool) -> i32 {
    let Some(lock) = std::fs::read_to_string(scope.lock()).ok().and_then(|t| serde_json::from_str::<Value>(&t).ok()) else {
        eprintln!("sync: lock unreadable");
        return 2;
    };
    let mut worst = 0;
    for (id, e) in lock["tools"].as_object().into_iter().flatten() {
        let route = e["route"].as_str().unwrap_or("");
        let version = e["version"].as_str().unwrap_or("");
        let package = e["packageId"].as_str().unwrap_or(id);
        let code = match route {
            "rustup-toolchain" => {
                let direct = |pkg: &str| run(&["rustup", "toolchain", "install", "--profile", "minimal", "--no-self-update", pkg]);
                if cand.has_mpm_files() {
                    let file = scope.packages();
                    let via = run(&["mpm", "--rustup", "restore", &file.to_string_lossy()]);
                    if via == 0 {
                        0
                    } else if fallback {
                        eprintln!("mpm restore failed ({via}); falling back to direct rustup");
                        direct(package)
                    } else {
                        via
                    }
                } else {
                    direct(package)
                }
            }
            "cargo-binstall" => run(&["cargo", "binstall", "--no-confirm", "--version", version, package]),
            "mpm-uvx" => run(&["uv", "tool", "install", &format!("{package}=={version}")]),
            "mpm-pnpm" => run(&["pnpm", "add", "--global", &format!("{package}@{version}")]),
            other => {
                eprintln!("sync: route {other} not implemented in the prototype");
                0
            }
        };
        if code != 0 {
            worst = code;
        }
    }
    worst
}

fn capture(args: &[&str]) -> String {
    Command::new(args[0]).args(&args[1..]).output().map(|o| String::from_utf8_lossy(&o.stdout).to_string()).unwrap_or_default()
}

/// Compares the lock with what is installed. Returns the number of mismatches.
pub fn status(scope: &Scope) -> usize {
    let Some(lock) = std::fs::read_to_string(scope.lock()).ok().and_then(|t| serde_json::from_str::<Value>(&t).ok()) else {
        println!("status: lock unreadable");
        return 1;
    };
    let rustup = capture(&["rustup", "toolchain", "list"]);
    let cargo = capture(&["cargo", "install", "--list"]);
    let uv = capture(&["uv", "tool", "list"]);
    let pnpm = capture(&["pnpm", "list", "--global", "--depth", "0", "--json"]);
    let mut bad = 0;
    for (id, e) in lock["tools"].as_object().into_iter().flatten() {
        let route = e["route"].as_str().unwrap_or("");
        let version = e["version"].as_str().unwrap_or("");
        let package = e["packageId"].as_str().unwrap_or(id);
        let ok = match route {
            "rustup-toolchain" => rustup.lines().any(|l| l.starts_with(&format!("{version}-"))),
            "cargo-binstall" => cargo.lines().any(|l| l.starts_with(&format!("{package} v{version}:"))),
            "mpm-uvx" => uv.lines().any(|l| l == format!("{package} v{version}")),
            "mpm-pnpm" => pnpm.contains(&format!("\"{package}\"")) && pnpm.contains(&format!("\"version\": \"{version}\"")),
            _ => true,
        };
        println!("{} {id} locked={version}", if ok { "MATCH   " } else { "MISMATCH" });
        if !ok {
            bad += 1;
        }
    }
    bad
}

//endregion sync and status
