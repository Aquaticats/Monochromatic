// PROTOTYPE (throwaway). Shared pieces for the two prototype binaries. Not production code.
//
// Candidates (see doc/planning/file-enforcer-rust-rewrite.md, mpm files question):
//   A: mpm-shadow writes lock + both mpm files; `mpm-shadow lock --check` is the drift gate; file-enforcer has no toolchain role.
//   B: as A, but `file-enforcer check` also verifies all three files through this shared library.
//   C: mpm-shadow writes the lock only and shells out to `file-enforcer write` (or `user write`) for the mpm files.
//   D: only the lock exists; mpm.packages.toml and mpm.managers.toml are not generated at all.

pub mod render;

use serde_json::{json, Map, Value};
use std::collections::BTreeMap;
use std::path::{Path, PathBuf};
use std::process::Command;
use std::time::Duration;

#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub enum Candidate {
    A,
    B,
    C,
    D,
}

impl Candidate {
    pub fn parse(text: &str) -> Result<Candidate, String> {
        match text {
            "a" | "A" => Ok(Candidate::A),
            "b" | "B" => Ok(Candidate::B),
            "c" | "C" => Ok(Candidate::C),
            "d" | "D" => Ok(Candidate::D),
            other => Err(format!("unknown candidate {other:?}")),
        }
    }
    pub fn shadow_writes_mpm_files(self) -> bool {
        matches!(self, Candidate::A | Candidate::B)
    }
    pub fn has_mpm_files(self) -> bool {
        !matches!(self, Candidate::D)
    }
    pub fn header(self) -> &'static str {
        match self {
            Candidate::A | Candidate::B => "# PROTOTYPE: generated by mpm-shadow from toolchain.lock.json.\n# Do not edit: run `mpm-shadow lock`.\n",
            Candidate::C => "# PROTOTYPE: generated by file-enforcer from toolchain.lock.json.\n# Do not edit: run `file-enforcer write`.\n",
            Candidate::D => "",
        }
    }
}

