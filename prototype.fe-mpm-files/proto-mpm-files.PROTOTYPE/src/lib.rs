pub fn write_atomic(path: &Path, content: &str, mode: u32) -> Result<(), String> {
    use std::os::unix::fs::PermissionsExt;
    let tmp = path.with_file_name(format!(".{}.tmp{}", path.file_name().unwrap().to_string_lossy(), std::process::id()));
    std::fs::write(&tmp, content).map_err(|e| format!("write {}: {e}", tmp.display()))?;
    std::fs::set_permissions(&tmp, std::fs::Permissions::from_mode(mode)).map_err(|e| e.to_string())?;
    std::fs::rename(&tmp, path).map_err(|e| format!("rename to {}: {e}", path.display()))
}

pub fn write_mpm_files(scope: &Scope, lock: &Value, header: &str) -> Result<(), String> {
    write_atomic(&scope.packages(), &render::render_packages(lock, header), 0o644)?;
    // The managers file is executable configuration and mpm refuses group/world writable files: 0600.
    write_atomic(&scope.managers(), &render::render_managers(lock, header), 0o600)
}

#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub enum Guard {
    None,
    Cas,
    Mutex,
}

pub fn sleep_ms(var: &str) {
    if let Some(ms) = std::env::var(var).ok().and_then(|v| v.parse::<u64>().ok()) {
        std::thread::sleep(Duration::from_millis(ms));
    }
}

fn hash(text: &str) -> u64 {
    use std::hash::{Hash, Hasher};
    let mut h = std::collections::hash_map::DefaultHasher::new();
    text.hash(&mut h);
    h.finish()
}

pub struct MutexFile(PathBuf);
impl Drop for MutexFile {
    fn drop(&mut self) {
        let _ = std::fs::remove_file(&self.0);
    }
}

fn acquire(path: &Path) -> Result<MutexFile, String> {
    for _ in 0..200 {
        match std::fs::OpenOptions::new().write(true).create_new(true).open(path) {
            Ok(_) => return Ok(MutexFile(path.to_path_buf())),
            Err(_) => std::thread::sleep(Duration::from_millis(50)),
        }
    }
    Err("could not take the lock-writer mutex within 10 s".into())
}

/// The lock write cycle shared by `lock` and `update`: read, project, (race sleep), guarded write, mpm files.
pub fn write_cycle(scope: &Scope, cand: Candidate, guard: Guard, resolutions: &BTreeMap<String, String>) -> Result<(), String> {
    let _mutex = if guard == Guard::Mutex { Some(acquire(&scope.dir.join(".toolchain.lock.writer"))?) } else { None };
    for attempt in 0..5 {
        let old_text = std::fs::read_to_string(scope.lock()).ok();
        let old: Option<Value> = match &old_text {
            Some(t) => Some(serde_json::from_str(t).map_err(|e| format!("lock: {e}"))?),
            None => None,
        };
        let plan = read_json(&scope.plan())?;
        let new = project(&plan, old.as_ref(), resolutions)?;
        sleep_ms("PROTO_RACE_SLEEP_MS");
        if guard == Guard::Cas {
            let now = std::fs::read_to_string(scope.lock()).ok();
            if now.as_deref().map(hash) != old_text.as_deref().map(hash) {
                eprintln!("lock changed under us (attempt {attempt}); re-reading and re-applying");
                continue;
            }
        }
        // Window between the compare and the rename: a compare-and-swap cannot close it, only the mutex does.
        sleep_ms("PROTO_RACE_SLEEP_AFTER_CHECK_MS");
        write_atomic(&scope.lock(), &lock_text(&new), 0o644)?;
        sleep_ms("PROTO_RACE_SLEEP_AFTER_LOCK_MS");
        if cand.shadow_writes_mpm_files() {
            write_mpm_files(scope, &new, cand.header())?;
        }
        return Ok(());
    }
    Err("lock kept changing; gave up after 5 attempts".into())
}

