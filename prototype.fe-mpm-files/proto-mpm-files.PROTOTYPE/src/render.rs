fn escape_char(ch: char, out: &mut String) {
    match ch {
        '\\' => out.push_str("\\\\"),
        '"' => out.push_str("\\\""),
        '\n' => out.push_str("\\n"),
        '\r' => out.push_str("\\r"),
        '\t' => out.push_str("\\t"),
        c if (c as u32) < 0x20 || (c as u32) == 0x7F => out.push_str(&format!("\\u{:04x}", c as u32)),
        c => out.push(c),
    }
}

pub fn toml_string(value: &str) -> String {
    let mut out = String::from("\"");
    for ch in value.chars() {
        escape_char(ch, &mut out);
    }
    out.push('"');
    out
}

pub fn toml_key(key: &str) -> String {
    let bare = !key.is_empty() && key.chars().all(|c| c.is_ascii_alphanumeric() || c == '_' || c == '-');
    if bare { key.to_string() } else { toml_string(key) }
}

fn manager_slug(id: &str) -> String {
    let bare = match id.find(':') {
        Some(i) => &id[i + 1..],
        None => id,
    };
    let separated: String = bare
        .to_lowercase()
        .chars()
        .map(|c| if c.is_ascii_lowercase() || c.is_ascii_digit() { c } else { ' ' })
        .collect();
    separated.split(' ').filter(|p| !p.is_empty()).collect::<Vec<_>>().join("-")
}

fn s<'a>(v: &'a Value, key: &str) -> Option<&'a str> {
    v.get(key).and_then(Value::as_str)
}

/// `header` is the leading comment block (already newline terminated).
pub fn render_packages(lock: &Value, header: &str) -> String {
    let mut by_manager: Vec<(String, Vec<(String, String)>)> = Vec::new();
    if let Some(tools) = lock.get("tools").and_then(Value::as_object) {
        for (_id, entry) in tools {
            let (Some(manager), Some(package_id), Some(version)) =
                (s(entry, "manager"), s(entry, "packageId"), s(entry, "version"))
            else {
                continue;
            };
            match by_manager.iter_mut().find(|(m, _)| m == manager) {
                Some((_, bucket)) => bucket.push((package_id.to_string(), version.to_string())),
                None => by_manager.push((manager.to_string(), vec![(package_id.to_string(), version.to_string())])),
            }
        }
    }
    by_manager.sort_by(|a, b| a.0.cmp(&b.0));
    let mut lines: Vec<String> = header.lines().map(str::to_string).collect();
    lines.push(String::new());
    for (manager, entries) in by_manager {
        lines.push(format!("[{}]", toml_key(&manager)));
        for (package_id, version) in entries {
            lines.push(format!("{} = {}", toml_key(&package_id), toml_string(&version)));
        }
        lines.push(String::new());
    }
    lines.join("\n")
}

/// Same header text as the TypeScript renderer's managers file, plus the fixed explanatory block.
pub fn render_managers(lock: &Value, header: &str) -> String {
    let mut lines: Vec<String> = header.lines().map(str::to_string).collect();
    for l in [
        "#",
        "# Trusted local manager definitions (owner-writable only): one per tool",
        "# whose exact pin a shipped MPM adapter would drop. Each install argument",
        "# list bakes the locked version next to {package_id}, the only pin channel",
        "# the MPM 8.2.0 definition schema allows.",
        "",
    ] {
        lines.push(l.to_string());
    }
    if let Some(tools) = lock.get("tools").and_then(Value::as_object) {
        for (id, entry) in tools {
            if s(entry, "route") != Some("cargo-binstall") {
                continue;
            }
            let route = "cargo-binstall";
            let version = s(entry, "version").unwrap_or("");
            let manager_id = format!("{}-{}", route, manager_slug(id));
            let linux = entry
                .get("os")
                .and_then(Value::as_array)
                .map(|a| a.iter().any(|o| o.as_str() == Some("linux")))
                .unwrap_or(false);
            let package_name = s(entry, "packageId").unwrap_or(id);
            let mut args = vec!["binstall".to_string(), "--no-confirm".into(), "--version".into(), version.to_string()];
            if let Some(features) = entry.pointer("/options/cargoFeatures").and_then(Value::as_array) {
                for f in features {
                    args.push("--features".into());
                    args.push(f.as_str().unwrap_or("").to_string());
                }
            }
            args.push("{package_id}".into());
            let q = |v: &[String]| v.iter().map(|a| toml_string(a)).collect::<Vec<_>>().join(", ");
            lines.push(format!("[mpm.overrides.{}]", toml_key(&manager_id)));
            lines.push(format!("name = {}", toml_string(&format!("{} {} {}", route, package_name, version))));
            lines.push(format!("platforms = [{}]", if linux { toml_string("linux") } else { toml_string("all_platforms") }));
            lines.push(format!("cli_names = [{}]", toml_string("cargo")));
            lines.push(String::new());
            lines.push(format!("[mpm.overrides.{}.operations.install]", toml_key(&manager_id)));
            lines.push(format!("args = [{}]", q(&args)));
            lines.push(String::new());
            lines.push(format!("[mpm.overrides.{}.operations.remove]", toml_key(&manager_id)));
            lines.push(format!("args = [{}]", q(&["uninstall".to_string(), "{package_id}".to_string()])));
            lines.push(String::new());
        }
    }
    lines.join("\n")
}
