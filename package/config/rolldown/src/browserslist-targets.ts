/**
 Resolves rolldown target strings from generated JSON, falling back to
 Browserslist, normalizing either source via
 {@link normalizeBrowserslistTargets}.
 
 @param generatedFileUrl - Generated JSON file URL.
 
 @param exists - Filesystem predicate used before importing generated JSON.
 
 @param importJson - Dynamic JSON importer.
 
 @param importBrowserslist - Dynamic Browserslist package importer.
 
 @param runtime - Runtime family whose targets should be returned.
 
 @returns Resolved Browserslist target strings for rolldown.
 
 @example
 ```ts
 const target = await browserslistTargets();
 ```
 */
export async function browserslistTargets({
  generatedFileUrl = GENERATED_BROWSERSLIST_URL,
  exists = generatedFileExists,
  importJson = importGeneratedJson,
  importBrowserslist = importBrowserslistPackage,
  runtime = 'browser',
}: BrowserslistTargetsOptions = {},): Promise<string[]> {
  if (await exists(generatedFileUrl,)) {
    /**
     Generated JSON default export.
     */
    const importedTargets = await importJson(generatedFileUrl,);

    return normalizeBrowserslistTargets({
      runtime,
      targets: assertStringArray({
        source: generatedFileUrl.href,
        value: importedTargets,
      },),
    },);
  }

  /**
   Browserslist package namespace imported when generated JSON is absent.
   */
  const importedBrowserslist = await importBrowserslist();
  /**
   Resolver extracted from runtime-specific dynamic import shape.
   */
  const resolveBrowserslist = browserslistResolver(importedBrowserslist,);

  return normalizeBrowserslistTargets({
    runtime,
    targets: resolveBrowserslist(
      undefined,
      { path: process.cwd(), },
    ),
  },);
}

