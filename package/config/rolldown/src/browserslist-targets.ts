/**
 Checks whether value is a string.
 
 @param value - Value being narrowed.
 
 @returns Whether value is a string.
 
 @example
 ```ts
 isString('firefox 140');
 ```
 */
function isString(value: unknown,): value is string {
  return (typeof value) === 'string';
}

/**
 Checks whether value is an array of strings.
 
 @param value - Value being narrowed.
 
 @returns Whether value is an array of strings.
 
 @example
 ```ts
 isStringArray(['firefox 140']);
 ```
 */
function isStringArray(value: unknown,): value is string[] {
  return (Array.isArray(value,))
    && (value.every(function isStringItem(item,): boolean {
      return isString(item,);
    },));
}

/**
 Asserts that imported targets are represented as a string array.
 
 @param value - Value loaded from generated JSON or dynamic fallback.
 
 @param source - Human-readable source included in validation failures.
 
 @returns String array when validation succeeds.
 
 @throws TypeError when value is not a string array.
 
 @example
 ```ts
 const targets = assertStringArray({ source: 'generated JSON', value: ['firefox 140'] });
 ```
 */
function assertStringArray({
  value,
  source,
}: StringArrayAssertionArgs,): string[] {
  if (isStringArray(value,))
    return value;

  throw new TypeError(`${source} must default-export a string array.`,);
}

/**
 Splits Browserslist target string into browser and version pieces.
 
 @param target - Browserslist target string to split.
 
 @returns Parsed browser, version, and original target.
 
 @throws TypeError when target cannot be split into browser and version.
 
 @example
 ```ts
 const parts = splitBrowserslistTarget('firefox 140');
 ```
 */
function splitBrowserslistTarget(target: string,): BrowserslistTargetParts {
  /**
   Index of separator between browser identifier and version string.
   */
  const separatorIndex = target.indexOf(' ',);

  if (separatorIndex === NOT_FOUND_INDEX)
    throw new TypeError(`Browserslist target is missing version: ${target}`,);

  /**
   Browser identifier before first space.
   */
  const browser = target.slice(
    0,
    separatorIndex,
  );
  /**
   Version identifier after first space.
   */
  const version = target.slice((separatorIndex + 1),);

  if (version.length === 0)
    throw new TypeError(`Browserslist target is missing version: ${target}`,);

  return {
    browser,
    original: target,
    version,
  };
}

/**
 Checks whether browser identifier has a Rolldown target mapping.
 
 @param browser - Browserslist browser identifier.
 
 @returns Whether identifier can be converted to a Rolldown target name.
 
 @example
 ```ts
 hasRolldownBrowserName('and_chr');
 ```
 */
function hasRolldownBrowserName(
  browser: string,
): browser is keyof typeof ROLLDOWN_BROWSER_NAMES {
  return Object.hasOwn(
    ROLLDOWN_BROWSER_NAMES,
    browser,
  );
}

/**
 Converts Browserslist browser identifier to Rolldown target name.
 
 @param parts - Parsed Browserslist target pieces.
 
 @returns Rolldown target browser name.
 
 @throws TypeError when browser identifier is unsupported by this mapping.
 
 @example
 ```ts
 const browser = rolldownBrowserName({ browser: 'and_chr', original: 'and_chr 148', version: '148' });
 ```
 */
function rolldownBrowserName(parts: BrowserslistTargetParts,): string {
  if (hasRolldownBrowserName(
    parts.browser,
  ))
    return ROLLDOWN_BROWSER_NAMES[parts.browser];

  throw new TypeError(
    `Browserslist target is unsupported by rolldown target mapping: ${parts.original}`,
  );
}

/**
 Compares dot-separated numeric version strings.
 
 @param left - Left-hand version string.
 
 @param right - Right-hand version string.
 
 @returns Negative when left is lower, positive when right is lower, zero when equal.
 
 @example
 ```ts
 compareVersions({ left: '140', right: '150' });
 ```
 */
function compareVersions({
  left,
  right,
}: VersionComparisonArgs,): number {
  /**
   Left version split into numeric-looking segments.
   */
  const leftParts = left.split('.',);
  /**
   Right version split into numeric-looking segments.
   */
  const rightParts = right.split('.',);
  /**
   Segment count needed to compare every present version component.
   */
  const length = Math.max(
    leftParts.length,
    rightParts.length,
  );

  for (let loopIndex = 0; loopIndex < length; loopIndex += 1) {
    /**
     Left segment number, defaulting absent trailing segments to zero.
     */
    const leftNumber = Number(leftParts[loopIndex] ?? '0',);
    /**
     Right segment number, defaulting absent trailing segments to zero.
     */
    const rightNumber = Number(rightParts[loopIndex] ?? '0',);

    if (Number.isNaN(leftNumber,))
      return left.localeCompare(right,);

    if (Number.isNaN(rightNumber,))
      return left.localeCompare(right,);

    if (leftNumber < rightNumber)
      return -1;

    if (leftNumber > rightNumber)
      return 1;
  }

  return 0;
}

/**
 Chooses lower target version within one Rolldown browser family.
 
 @param current - Existing target selected for browser family.
 
 @param candidate - Candidate target being compared against existing target.
 
 @returns Lower-version target.
 
 @example
 ```ts
 const lower = lowerTarget({ current, candidate });
 ```
 */
function lowerTarget({
  current,
  candidate,
}: LowerTargetArgs,): RolldownTargetParts {
  /**
   Version comparison where negative means candidate is lower.
   */
  const comparison = compareVersions({
    left: candidate.version,
    right: current.version,
  },);

  if (comparison < 0)
    return candidate;

  return current;
}

/**
 Converts one Browserslist target string to Rolldown target pieces by
 splitting it with {@link splitBrowserslistTarget} and mapping the browser
 identifier through {@link rolldownBrowserName}.
 
 @param target - Browserslist target string to convert.
 
 @returns Rolldown target pieces accepted by rolldown's `transform.target`.
 
 @example
 ```ts
 normalizeBrowserslistTarget('and_chr 148');
 ```
 */
function normalizeBrowserslistTarget(target: string,): RolldownTargetParts {
  /**
   Parsed target pieces used for name mapping and formatting.
   */
  const parts = splitBrowserslistTarget(target,);
  /**
   Rolldown target browser identifier.
   */
  const browser = rolldownBrowserName(parts,);

  return {
    browser,
    original: parts.original,
    version: parts.version,
  };
}

/**
 Formats Rolldown target pieces as a rolldown target string.
 
 @param target - Rolldown target pieces to format.
 
 @returns Target string accepted by rolldown's `transform.target`.
 
 @example
 ```ts
 const target = formatRolldownTarget({ browser: 'firefox', original: 'firefox 140', version: '140' });
 ```
 */
function formatRolldownTarget(target: RolldownTargetParts,): string {
  return `${target.browser}${target.version}`;
}

/**
 Selects lowest version for each Rolldown browser family.
 
 @param targets - Rolldown target pieces to collapse by browser family.
 
 @returns Map keyed by browser family with lowest selected target.
 
 @example
 ```ts
 const targetMap = lowestTargetsByBrowser([]);
 ```
 */
function lowestTargetsByBrowser(
  targets: readonly RolldownTargetParts[],
): Map<string, RolldownTargetParts> {
  /**
   Mutable target map scoped to this reduction.
   */
  const targetMap = new Map<string, RolldownTargetParts>();

  for (const candidate of targets) {
    /**
     Current target selected for this browser family, if any.
     */
    const current = targetMap.get(candidate.browser,);

    targetMap.set(
      candidate.browser,
      current === undefined
        ? candidate
        : lowerTarget({
          candidate,
          current,
        },),
    );
  }

  return targetMap;
}

/**
 Checks whether normalized target belongs to requested runtime family.
 
 @param runtime - Runtime family requested by the rolldown build flavor.
 
 @param target - Target pieces being checked.
 
 @returns Whether target should be used for runtime family.
 
 @example
 ```ts
 targetMatchesRuntime({ runtime: 'node', target });
 ```
 */
function targetMatchesRuntime({
  runtime,
  target,
}: RuntimeTargetArgs,): boolean {
  if (runtime === 'node')
    return target.browser === 'node';

  return target.browser !== 'node';
}

/**
 Throws when runtime filtering removes every target.
 
 @param runtime - Runtime family requested by the rolldown build flavor.
 
 @param targets - Runtime-filtered target pieces.
 
 @returns Same targets when non-empty.
 
 @throws TypeError when runtime family has no matching targets.
 
 @example
 ```ts
 const targets = assertRuntimeTargets({ runtime: 'browser', targets: [target] });
 ```
 */
function assertRuntimeTargets({
  runtime,
  targets,
}: {
  readonly runtime: TargetRuntime;
  readonly targets: readonly RolldownTargetParts[];
},): readonly RolldownTargetParts[] {
  if (targets.length > 0)
    return targets;

  throw new TypeError(`Browserslist config produced no ${runtime} targets for rolldown.`,);
}

/**
 Converts Browserslist output to unique Rolldown-compatible targets,
 collapsing each browser family to its lowest version via
 {@link lowestTargetsByBrowser}.
 
 @param targets - Raw target strings returned by Browserslist.
 
 @param runtime - Runtime family requested by the rolldown build flavor.
 
 @returns Unique rolldown target strings.
 
 @example
 ```ts
 const targets = normalizeBrowserslistTargets({ runtime: 'browser', targets: ['and_chr 148'] });
 ```
 */
function normalizeBrowserslistTargets({
  runtime,
  targets,
}: NormalizeTargetsArgs,): string[] {
  /**
   Rolldown target pieces in Browserslist output order.
   */
  const mappedTargets = targets.map(function normalizeTarget(target,): RolldownTargetParts {
    return normalizeBrowserslistTarget(target,);
  },);
  /**
   Rolldown target pieces matching requested runtime family.
   */
  const runtimeTargets = assertRuntimeTargets({
    runtime,
    targets: mappedTargets.filter(function filterRuntimeTarget(target,): boolean {
      return targetMatchesRuntime({
        runtime,
        target,
      },);
    },),
  },);
  /**
   Map holding lowest target pieces per Rolldown browser family.
   */
  const lowestTargetMap = lowestTargetsByBrowser(runtimeTargets,);
  /**
   Lowest target pieces per Rolldown browser family.
   */
  const lowestTargets = [...lowestTargetMap.values(),];

  return lowestTargets.map(function formatTarget(target,): string {
    return formatRolldownTarget(target,);
  },);
}

/**
 Extracts resolver function from possible Browserslist import shapes.
 
 @param imported - Browserslist dynamic import namespace or callable export.
 
 @returns Browserslist resolver function.
 
 @example
 ```ts
 const resolveBrowserslist = browserslistResolver({ default: browserslist });
 ```
 */
function browserslistResolver(imported: BrowserslistImport,): BrowserslistResolver {
  if ((typeof imported) === 'function')
    return imported;

  return imported.default;
}

