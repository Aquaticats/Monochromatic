/**
 Extracts default export from dynamic JSON module namespace.
 
 @param imported - Runtime module namespace to inspect.
 
 @param source - Human-readable source included in validation failures.
 
 @returns Default export value.
 
 @throws TypeError when module namespace has no default export.
 
 @example
 ```ts
 const value = jsonModuleDefault({ imported: { default: [] }, source: 'json' });
 ```
 */
function jsonModuleDefault({
  imported,
  source,
}: JsonModuleDefaultArgs,): unknown {
  if ((typeof imported) !== 'object')
    throw new TypeError(`${source} must provide a default export.`,);

  if (imported === null)
    throw new TypeError(`${source} must provide a default export.`,);

  if (!('default' in imported))
    throw new TypeError(`${source} must provide a default export.`,);

  return imported.default;
}

/**
 Imports generated Browserslist target JSON, reading the default export
 out via {@link jsonModuleDefault}.
 
 @param fileUrl - Generated JSON file URL to import.
 
 @returns Default export from JSON module namespace.
 
 @example
 ```ts
 const imported = await importGeneratedJson(new URL('file:///tmp/targets.json'));
 ```
 */
async function importGeneratedJson(fileUrl: URL,): Promise<unknown> {
  /**
   JSON namespace loaded through import attributes.
   */
  const imported: unknown = await import(
    fileUrl.href,
    { with: { type: 'json', }, },
  );

  return jsonModuleDefault({
    imported,
    source: fileUrl.href,
  },);
}

/**
 Imports Browserslist package for live target resolution.
 
 @returns Browserslist package namespace from dynamic import.
 
 @example
 ```ts
 const imported = await importBrowserslistPackage();
 ```
 */
async function importBrowserslistPackage(): Promise<BrowserslistImport> {
  /**
   CommonJS package namespace exposed through ESM dynamic import.
   */
  const imported = await import('browserslist') as BrowserslistImport;

  return imported;
}

