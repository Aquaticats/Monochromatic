/**
 Deterministic generators for the MPM manifests:

 - `mpm.packages.toml`: `mpm dump` format, one section per MPM manager id,
   entries `package_id = "<version>"`, the declared desired state of every
   managed tool. Entries carry bare package ids and version values: no
   `@version` pin syntax (the user-confirmed "no pinning" wording), because
   `toolchain.lock.json` is what fixes the installed versions.
 - `mpm.managers.toml`: trusted local manager definitions under
   `[mpm.overrides.<id>]`, one per `cargo:` tool whose exact pin the shipped
   MPM `cargo` adapter would drop (it warns `does not implement version
   parameter` and installs unpinned;
   `doc/troubleshooting/mpm-manager-extensibility.md`). Each definition bakes
   the locked version into a `--version` argument, the pin channel MPM 8.2.0's
   definition schema allows (`{version}` is rejected, and `@version` package
   spec syntax stays out of declarations). The `pnpm` adapter also drops
   versions, but its only pin channel is `@version` package syntax, so those
   tools stay provider-owned at the repository boundary instead of carrying a
   definition.
 */

import type { ToolPlanEntry, } from './types.ts';

//region TOML primitives

/**
 First code point TOML allows unescaped in a basic string; lower ones are control characters.
 */
const FIRST_PRINTABLE_CODE = 0x20;

/**
 The DEL control character, which TOML basic strings also require escaped.
 */
const DELETE_CODE = 0x7F;

/**
 Hex digits in a `\uXXXX` escape.
 */
const UNICODE_ESCAPE_DIGITS = 4;

/**
 Characters a bare TOML key may use.
 */
const BARE_KEY_CHARACTERS = 'ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789_-';

/**
 Characters a local manager slug keeps; every other character separates slug parts.
 */
const SLUG_CHARACTERS = 'abcdefghijklmnopqrstuvwxyz0123456789';

/**
 Escapes one character for use inside a TOML basic string.

 @param ch - One code point of the raw string

 @returns The character, or its escape when TOML requires one
 */
function escapeTomlCharacter(ch: string,): string {
  /**
   Code point of the character.
   */
  const code = ch.codePointAt(0,) ?? 0;
  if (ch === '\\')
    return String.raw`\\`;
  if (ch === '"')
    return String.raw`\"`;
  if (ch === '\n')
    return String.raw`\n`;
  if (ch === '\r')
    return String.raw`\r`;
  if (ch === '\t')
    return String.raw`\t`;
  if ((code < FIRST_PRINTABLE_CODE) || (code === DELETE_CODE))
    return `\\u${code.toString(16,)
      .padStart(
        UNICODE_ESCAPE_DIGITS,
        '0',
      )}`;
  return ch;
}

/**
 Escapes one string as a TOML basic string, including the surrounding quotes.

 Backslash, double quote, and control characters are encoded as `\\`, `\"`,
 and `\uXXXX` escapes, so arbitrary plan data cannot break out of the literal.

 @param value - Raw string to encode

 @returns Quoted TOML string literal

 @example
 ```ts
 tomlString('say "hi"',); // '"say \\"hi\\""'
 ```
 */
export function tomlString(value: string,): string {
  /**
   Escaped code points, in order.
   */
  const escaped: string[] = [];
  for (const ch of value)
    escaped.push(escapeTomlCharacter(ch,),);
  return `"${escaped.join('',)}"`;
}

/**
 Renders one TOML key: bare when the grammar allows it, quoted otherwise.

 @param key - Table key to render

 @returns TOML key text

 @example
 ```ts
 tomlKey('fd-find',); // 'fd-find'
 tomlKey('@actions/languageserver',); // '"@actions/languageserver"'
 ```
 */
export function tomlKey(key: string,): string {
  if (key.length === 0)
    return tomlString(key,);
  for (const ch of key) {
    if (!BARE_KEY_CHARACTERS.includes(ch,))
      return tomlString(key,);
  }
  return key;
}

//endregion TOML primitives

//region mpm.packages.toml

/**
 Renders `mpm.packages.toml` from the plan.

 Sections are the MPM manager ids in sorted order; entries inside a section
 keep plan order. The header carries no timestamp, so repeated runs are
 byte-identical.
 
 @param tools - Plan entries to declare
 
 @returns TOML text

 @example
 ```ts
 renderMpmPackagesToml({ tools: ALL_TOOLS, },); // '# Generated by ...\n[cargo]\nfd-find = "10.5.0"\n...'
 ```
 */
export function renderMpmPackagesToml(
  { tools, }: { readonly tools: readonly ToolPlanEntry[]; },
): string {
  /**
   Manager id to entries, preserving plan order per manager.
   */
  const byManager = new Map<string, ToolPlanEntry[]>();
  for (const entry of tools) {
    if ((entry.manager === undefined) || (entry.packageId === undefined))
      continue;
    /**
     Existing bucket for this manager, or a fresh one.
     */
    const bucket = byManager.get(entry.manager,);
    if (bucket === undefined)
      byManager.set(
        entry.manager,
        [entry],
      );
    else
      bucket.push(entry,);
  }

  /**
   Rendered lines, joined with newlines at the end.
   */
  const lines: string[] = [
    '# Generated by package/file-enforcer/core/src/toolchain/generate.ts.',
    '# Do not edit: regenerate from the typed tool plan.',
    '',
  ];
  for (const manager of [...byManager.keys()].toSorted()) {
    lines.push(`[${tomlKey(manager,)}]`,);
    for (const entry of byManager.get(manager,) ?? []) {
      lines.push(
        `${tomlKey(entry.packageId ?? '',)} = ${tomlString(entry.version,)}`,
      );
    }
    lines.push('',);
  }
  return lines.join('\n',);
}

//endregion mpm.packages.toml

//region mpm.managers.toml

/**
 Slug used in a local manager id: lowercase letters, digits and hyphens.

 @param id - Plan tool id, optionally with a backend prefix such as `cargo:`

 @returns The id without its prefix, lowercased, with every run of other characters collapsed to one hyphen and
 none at either end
 */
function managerSlug(id: string,): string {
  /**
   Tool id without its backend prefix.
   */
  const bare = id.includes(':',)
    ? id.slice(id.indexOf(':',) + 1,)
    : id;
  /**
   Lowercased code points, with every character outside the slug alphabet replaced by a separator.
   */
  const separated: string[] = [];
  for (const ch of bare.toLowerCase())
    separated.push(SLUG_CHARACTERS.includes(ch,)
      ? ch
      : ' ',);
  return separated.join('',)
    .split(' ',)
    .filter(
    function isSlugPart(part,): boolean {
      return part !== '';
    },
    )
    .join('-',);
}

/**
 Tools whose exact pin a definition can express and a shipped MPM adapter drops.

 Only the `cargo:` tools qualify: the shipped `cargo` adapter warns and
 installs unpinned, while a definition can bake `--version`. The `pnpm`
 adapter also drops pins, but only `@version` package syntax could carry them,
 which the user-confirmed "no pinning" wording keeps out of declarations.

 @param entry - Plan entry to test

 @returns `true` when the entry installs through `cargo binstall`
 */
function needsPinDefinition(entry: ToolPlanEntry,): boolean {
  return entry.route === 'cargo-binstall';
}

/**
 Builds the `install` argument vector for one pin-expressing definition,
 baking the locked version in a `--version` argument next to the
 `{package_id}` placeholder.
 
 @param entry - Plan entry to express

 @returns CLI arguments for the definition's `install` operation
 */
function installArgs(entry: ToolPlanEntry,): readonly string[] {
  /**
   `cargo binstall` arguments: exact `--version`, optional `--features`,
   then the crate id placeholder.
   */
  const args = [
    'binstall',
    '--no-confirm',
    '--version',
    entry.version,
  ];
  for (const feature of entry.options
    .cargoFeatures
    ?? []) {
    args.push(
      '--features',
      feature,
    );
  }
  args.push('{package_id}',);
  return args;
}

/**
 CLI arguments for the definition `remove` operation.

 @returns `cargo uninstall` arguments with the crate id placeholder
 */
function removeArgs(): readonly string[] {
  return [
    'uninstall',
    '{package_id}'
  ];
}

/**
 Renders `mpm.managers.toml` from the plan.

 One `[mpm.overrides.<id>]` definition per tool whose pin a shipped adapter
 drops, in plan order. Each definition is executable configuration and stays
 owner-writable only (MPM's trust gate); `mpm --validate-config` accepts it.
 
 @param tools - Plan entries to express
 
 @returns TOML text

 @example
 ```ts
 renderMpmManagersToml({ tools: ALL_TOOLS, },); // '# Generated by ...\n[mpm.overrides.cargo-binstall-fd-find]\n...'
 ```
 */
export function renderMpmManagersToml(
  { tools, }: { readonly tools: readonly ToolPlanEntry[]; },
): string {
  /**
   Rendered lines, joined with newlines at the end.
   */
  const lines: string[] = [
    '# Generated by package/file-enforcer/core/src/toolchain/generate.ts.',
    '# Do not edit: regenerate from the typed tool plan.',
    '#',
    '# Trusted local manager definitions (owner-writable only): one per tool',
    '# whose exact pin a shipped MPM adapter would drop. Each install argument',
    '# list bakes the locked version next to {package_id}, the only pin channel',
    '# the MPM 8.2.0 definition schema allows.',
    '',
  ];
  for (const entry of tools) {
    if (!needsPinDefinition(entry,))
      continue;
    /**
     Local manager id for this pin-expressing definition.
     */
    const managerId = `${entry.route}-${managerSlug(entry.id,)}`;
    lines.push(
      `[mpm.overrides.${tomlKey(managerId,)}]`,
      `name = ${tomlString(`${entry.route} ${entry.packageId ?? entry.id} ${entry.version}`,)}`,
      `platforms = [${
        (entry.os ?? []).includes('linux',)
          ? tomlString('linux',)
          : tomlString('all_platforms',)
      }]`,
      `cli_names = [${tomlString('cargo',)}]`,
      '',
      `[mpm.overrides.${tomlKey(managerId,)}.operations.install]`,
      `args = [${
      installArgs(entry,)
        .map(tomlString,)
        .join(', ',)
    }]`,
      '',
      `[mpm.overrides.${tomlKey(managerId,)}.operations.remove]`,
      `args = [${
      removeArgs()
        .map(tomlString,)
        .join(', ',)
    }]`,
      ''
    );
  }
  return lines.join('\n',);
}

//endregion mpm.managers.toml
