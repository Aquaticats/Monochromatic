import { resolve, } from 'node:path';
import { hashContent, } from './staleness-hash.ts';
import { readFileStamps, } from './staleness-stamps.ts';
import {
  ABSENT_FILE_STAMPS,
  type DestinationStamp,
  type StalenessDestination,
} from './staleness-types.ts';

/**
 Returns destination stamps with content hashes attached: combines filesystem
 metadata from {@link readFileStamps} with hashes from {@link hashContent}.
 
 @param destinations - Destinations generated by a builder.
 
 @returns Persistable destination metadata, or the {@link ABSENT_FILE_STAMPS}
 sentinel when a destination is absent.
 
 @example
 ```ts
 const stamps = await destinationStamps([{ path: './out', content: 'x' }]);
 ```
 */
export async function destinationStamps(
  destinations: readonly StalenessDestination[],
): Promise<readonly DestinationStamp[] | typeof ABSENT_FILE_STAMPS> {
  /**
   Metadata for each destination path.
   */
  const destinationPaths = destinations.map(function destinationPath(destination,): string {
    return destination.path;
  },);
  /**
   Filesystem metadata for destination paths.
   */
  const stamps = await readFileStamps(destinationPaths,);
  if (stamps === ABSENT_FILE_STAMPS)
    return ABSENT_FILE_STAMPS;

  /**
   Content hashes keyed by absolute destination path.
   */
  const hashesByPath = new Map<string, string>(
    destinations.map(function destinationHash(destination,): readonly [
      string,
      string,
    ] {
      return [
        resolve(destination.path,),
        hashContent(destination.content,),
      ];
    },),
  );

  return stamps.map(function attachHash(stamp,): DestinationStamp {
    return {
      ...stamp,
      hash: hashesByPath.get(stamp.path,)
        ?? hashContent('',),
    };
  },);
}
