//! What:
//!  Answer "which rules read or write this path?"
//! from a plan.
//! Why:
//!  `explain <path>` names the rule that generates a file and the rules that read it,
//! from what the plan recorded,
//!  so the answer cannot disagree with what `write` would do.
//!
//! In TS you'd write (pseudocode):
//! ```ts
//! function explain(report: PlanReport, path: string): Event[]
//! ```

/// Imports `Event` from `crate::event`.
use crate::event::Event;
/// Imports `PlanReport` from `crate::plan`.
use crate::plan::PlanReport;
/// Imports `Value` from `serde_json`.
use serde_json::Value;

/// What:
///  Turn a command-line path into a repo-relative path:
/// strip a leading `./` and the worktree root prefix.
/// Why:
///  People type `./CLAUDE.md` or an absolute path.
///
/// In TS you'd write (pseudocode):
/// ```ts
/// function normalizeTarget(root: string, path: string): string
/// ```
pub fn normalize_target(root: &std::path::Path, path: &str) -> String {
    let mut text = path.to_string();
    let prefix = format!("{}/", root.display());
    if let Some(rest) = text.strip_prefix(&prefix) {
        text = rest.to_string();
    }
    while let Some(rest) = text.strip_prefix("./") {
        text = rest.to_string();
    }
    return text.trim_end_matches('/').to_string();
}

/// What:
///  List the `explain` events for one path.
/// Why:
///  A path can be a rule's output,
/// a file or directory some rule read,
/// or both.
///
/// In TS you'd write (pseudocode):
/// ```ts
/// function explain(report: PlanReport, path: string): Event[]
/// ```
pub fn explain(report: &PlanReport, path: &str) -> Vec<Event> {
    let mut events: Vec<Event> = Vec::new();
    if let Some(rule_id) = report.owners.get(path) {
        let kind = report.rules.iter().find(|pair| return &pair.0 == rule_id).map(|pair| return pair.1.clone());
        let message = format!("{path} is generated by rule {rule_id}");
        let mut event = Event::new("explain", "explain-output", &message);
        event.set_field("path", Value::String(path.to_string()));
        event.set_field("rule", Value::String(rule_id.clone()));
        event.set_field("kind", Value::String(kind.unwrap_or_default()));
        event.set_field("role", Value::String("output".to_string()));
        events.push(event);
    }
    let mut readers: Vec<String> = Vec::new();
    for (index, read_path) in report.view.accesses() {
        if read_path == path
            && let Some((rule_id, _)) = report.rules.get(*index)
            && !readers.contains(rule_id)
            && report.owners.get(path) != Some(rule_id)
        {
            readers.push(rule_id.clone());
        }
    }
    for rule_id in readers {
        let message = format!("{path} is read by rule {rule_id}");
        let mut event = Event::new("explain", "explain-input", &message);
        event.set_field("path", Value::String(path.to_string()));
        event.set_field("rule", Value::String(rule_id));
        event.set_field("role", Value::String("input".to_string()));
        events.push(event);
    }
    if events.is_empty() {
        let message = format!("no rule reads or writes {path}");
        let mut event = Event::new("explain", "explain-none", &message);
        event.set_field("path", Value::String(path.to_string()));
        events.push(event);
    }
    return events;
}
