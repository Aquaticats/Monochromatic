/**
 What the driver makes of the failures a model reports, read against the texts real runs recorded.

 @module
 */

import {
  describe,
  expect,
  it,
} from '@monochromatic-dev/test-harness-core/ts';
import {
  anotherAttemptMayFix,
  continuationPromptOf,
  isRateLimit,
  kindOfModelError,
  MODEL_ERROR_RETRY_BASE_SECONDS,
  MODEL_ERROR_RETRY_MAX_DELAY_MILLISECONDS,
  retryDelayMilliseconds,
  waitAskedByProvider,
} from '../dist/final/node/index.mjs';

/**
 The error one real run recorded, word for word from `pi-runs/policy-and-candidate-route-findings-on-main-1/feed.jsonl` on
 2026-11-09. It says `"retryable":true` and asks for a backoff of at least 60 seconds.
 */
const CLOUDFLARE_520 =
  '520 {"type":"https://developers.cloudflare.com/support/troubleshooting/http-status-codes/cloudflare-5xx-errors/error-520/","title":"Error 520: Web server is returning an unknown error","status":520,"detail":"The origin web server sent a response that Cloudflare could not parse. This may indicate the origin returned an empty response, malformed HTTP headers, or an otherwise invalid response.","instance":"a57aee4c687ca228","error_code":520,"error_name":"unknown_origin_error","error_category":"origin","ray_id":"a57aee4c687ca228","timestamp":"2026-11-09T06:58:45Z","zone":"api.neuralwatt.com","cloudflare_error":true,"retryable":true,"retry_after":60,"owner_action_required":true,"what_you_should_do":"**Wait and retry.** Back off for at least 60 seconds. If the error persists, the website operator should check the origin server error logs and submit them to Cloudflare support.","footer":"This error was generated by Cloudflare on behalf of the website owner."}';

/**
 The timeout one real run recorded, word for word from `pi-runs/repo-read-and-index-route-findings-on-main-1/summary.json`.
 */
const REQUEST_TIMED_OUT = 'Request timed out.';

/**
 The permanent failure three real runs recorded, word for word from `pi-runs/toml-edit-wrapped-values-validated-1/summary.json`.
 */
const PROVIDER_NOT_CONFIGURED = 'Provider is not configured: neuralwatt';

/**
 The abort a coordinator asks for, as a real run recorded it in `pi-runs/btrfs-ladder-host-run-1/feed.jsonl`.
 */
const OPERATION_ABORTED = 'This operation was aborted';

/**
 A rate limit, shaped as gateways send it.
 */
const TOO_MANY_REQUESTS = '429 {"error":{"message":"Too many requests"}}';

/**
 A plan limit sent as a rate limit, which another attempt cannot refill.
 */
const QUOTA_EXCEEDED = '429 {"error":{"code":"insufficient_quota","message":"You exceeded your current quota"}}';

await describe({
  name: kindOfModelError.name,
  children: [
    it({
      name: 'reads a server error and a timeout as failures another attempt can fix',
      fn: async () => {
        expect(kindOfModelError(CLOUDFLARE_520,),).toBe('transient',);
        expect(kindOfModelError(REQUEST_TIMED_OUT,),).toBe('transient',);
        expect(kindOfModelError('socket hang up',),).toBe('transient',);
        expect(kindOfModelError('503 Service Unavailable',),).toBe('transient',);
      },
    },),
    it({
      name: 'reads a missing provider and a requested abort as failures another attempt cannot fix',
      fn: async () => {
        expect(kindOfModelError(PROVIDER_NOT_CONFIGURED,),).toBe('permanent',);
        expect(kindOfModelError(OPERATION_ABORTED,),).toBe('permanent',);
        expect(kindOfModelError('context window exceeded',),).toBe('permanent',);
      },
    },),
    it({
      name: 'reads a rate limit apart from other failures, whether or not another attempt can fix it',
      fn: async () => {
        expect(kindOfModelError(TOO_MANY_REQUESTS,),).toBe('throttled',);
        expect(kindOfModelError(QUOTA_EXCEEDED,),).toBe('quota-reached',);
        expect(anotherAttemptMayFix('throttled',),).toBe(true,);
        expect(anotherAttemptMayFix('quota-reached',),).toBe(false,);
        expect(isRateLimit('throttled',),).toBe(true,);
        expect(isRateLimit('quota-reached',),).toBe(true,);
        expect(isRateLimit('transient',),).toBe(false,);
      },
    },),
    it({
      name: 'reads a status code hung on a number that is no status as no failure of its own',
      fn: async () => {
        expect(kindOfModelError('the request held 15203 tokens',),).toBe('permanent',);
        expect(kindOfModelError('retry 5203 later',),).toBe('permanent',);
      },
    },),
  ],
},);

await describe({
  name: retryDelayMilliseconds.name,
  children: [
    it({
      name: 'doubles the first delay with each attempt',
      fn: async () => {
        const delays = [1, 2, 3,].map(function delayOf(retryNumber,) {
          return retryDelayMilliseconds({
            problem: REQUEST_TIMED_OUT,
            retryNumber,
            baseSeconds: MODEL_ERROR_RETRY_BASE_SECONDS,
          },);
        },);
        expect(delays,).toEqual([2_000, 4_000, 8_000,],);
      },
    },),
    it({
      name: 'waits as long as the provider asked, within the largest delay',
      fn: async () => {
        expect(waitAskedByProvider(CLOUDFLARE_520,),).toEqual({
          asked: true,
          milliseconds: 60_000,
        },);
        expect(waitAskedByProvider('Retry-After: 30',),).toEqual({
          asked: true,
          milliseconds: 30_000,
        },);
        expect(waitAskedByProvider(REQUEST_TIMED_OUT,),).toEqual({ asked: false, },);
        expect(retryDelayMilliseconds({
          problem: CLOUDFLARE_520,
          retryNumber: 1,
          baseSeconds: MODEL_ERROR_RETRY_BASE_SECONDS,
        },),).toBe(MODEL_ERROR_RETRY_MAX_DELAY_MILLISECONDS,);
        expect(retryDelayMilliseconds({
          problem: 'Retry-After: 3600',
          retryNumber: 1,
          baseSeconds: MODEL_ERROR_RETRY_BASE_SECONDS,
        },),).toBe(MODEL_ERROR_RETRY_MAX_DELAY_MILLISECONDS,);
      },
    },),
    it({
      name: 'never grows past the largest delay',
      fn: async () => {
        expect(retryDelayMilliseconds({
          problem: REQUEST_TIMED_OUT,
          retryNumber: 60,
          baseSeconds: MODEL_ERROR_RETRY_BASE_SECONDS,
        },),).toBe(MODEL_ERROR_RETRY_MAX_DELAY_MILLISECONDS,);
      },
    },),
  ],
},);

await describe({
  name: continuationPromptOf.name,
  children: [
    it({
      name: 'names the failure and asks for the work to go on',
      fn: async () => {
        const prompt = continuationPromptOf({ problem: REQUEST_TIMED_OUT, },);
        expect(prompt,).toContain(REQUEST_TIMED_OUT,);
        expect(prompt,).toContain('Continue the task from where you left off',);
      },
    },),
    it({
      name: 'cuts a long failure rather than carrying all of it',
      fn: async () => {
        const prompt = continuationPromptOf({ problem: CLOUDFLARE_520, },);
        expect(prompt.length,).toBeLessThan(CLOUDFLARE_520.length,);
        expect(prompt,).toContain('...[',);
      },
    },),
  ],
},);
