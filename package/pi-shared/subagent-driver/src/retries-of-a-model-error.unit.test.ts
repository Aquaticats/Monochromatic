await describe({
  name: kindOfModelError.name,
  children: [
    it({
      name: 'reads a server error and a timeout as failures another attempt can fix',
      fn: async () => {
        expect(kindOfModelError(CLOUDFLARE_520,),).toBe('transient',);
        expect(kindOfModelError(REQUEST_TIMED_OUT,),).toBe('transient',);
        // A text Pi's own retry list holds, `@earendil-works/pi-ai/dist/utils/retry.js:74`.
        expect(kindOfModelError('socket hang up',),).toBe('transient',);
        // Made up, no program's output: the reason phrase of status 503, which no run here recorded; the boundary is a server
        // failure another attempt can fix.
        expect(kindOfModelError('503 Service Unavailable',),).toBe('transient',);
      },
    },),
    it({
      name: 'reads a missing provider and a requested abort as failures another attempt cannot fix',
      fn: async () => {
        expect(kindOfModelError(PROVIDER_NOT_CONFIGURED,),).toBe('permanent',);
        expect(kindOfModelError(OPERATION_ABORTED,),).toBe('permanent',);
        // A text Pi's own overflow detector recognises, `@earendil-works/pi-ai/dist/utils/overflow.js:44`.
        expect(kindOfModelError('context window exceeded',),).toBe('permanent',);
      },
    },),
    it({
      name: 'reads a rate limit apart from other failures, whether or not another attempt can fix it',
      fn: async () => {
        expect(kindOfModelError(SYNTHETIC_CONCURRENT_429,),).toBe('throttled',);
        expect(kindOfModelError(QUOTA_EXCEEDED,),).toBe('quota-reached',);
        expect(isRateLimit('throttled',),).toBe(true,);
        expect(isRateLimit('quota-reached',),).toBe(true,);
        expect(isRateLimit('transient',),).toBe(false,);
      },
    },),
    it({
      name: 'leaves every rate limit to Pi\'s own automatic retry, whatever kind of limit it names',
      fn: async () => {
        // The 429 a real run met: a concurrency limit rather than a quota, which Pi's own retry answers.
        expect(kindOfModelError(NEURALWATT_FLEX_429,),).toBe('throttled',);
        expect(driverRetries({ kind: 'throttled', problem: NEURALWATT_FLEX_429, },),).toBe(false,);
        expect(driverRetries({ kind: 'quota-reached', problem: QUOTA_EXCEEDED, },),).toBe(false,);
        // A 429 behind the prefix Pi's own composer writes is the same 429, whatever kind the text reads as otherwise.
        expect(kindOfModelError(PROVIDER_PREFIXED_429,),).toBe('throttled',);
        expect(driverRetries({ kind: 'throttled', problem: PROVIDER_PREFIXED_429, },),).toBe(false,);
        expect(driverRetries({ kind: 'transient', problem: PROVIDER_PREFIXED_429, },),).toBe(false,);
        // The control: a failure that is no 429 stays the driver's own to answer, and one no attempt can fix never is.
        expect(driverRetries({ kind: 'transient', problem: REQUEST_TIMED_OUT, },),).toBe(true,);
        expect(driverRetries({ kind: 'permanent', problem: PROVIDER_NOT_CONFIGURED, },),).toBe(false,);
        // A rate limit word in a failure that names no 429 keeps the attempt it had before, and a number that is no status
        // names no limit at all.
        expect(driverRetries({ kind: 'throttled', problem: RATE_LIMIT_WORD_AND_NO_429, },),).toBe(true,);
        expect(driverRetries({ kind: 'transient', problem: TOKEN_COUNT_HOLDING_4290, },),).toBe(true,);
        expect(driverRetries({ kind: 'transient', problem: TOKEN_COUNT_OF_429, },),).toBe(false,);
      },
    },),
    it({
      name: 'reads a failure that names a terminal cause before the transient words it also holds',
      fn: async () => {
        // Made up, no program's output: a bad credential beside a word about the upstream provider; the boundary is the
        // terminal cause read before the transient words beside it.
        expect(kindOfModelError('Invalid API key for upstream provider',),).toBe('permanent',);
        // Made up, no program's output: a context-length failure whose 500 is a count of tokens, not a status.
        expect(kindOfModelError('Context length exceeds the limit of 500 tokens',),).toBe('permanent',);
        // Made up, no program's output: an unknown model whose name holds a transient word.
        expect(kindOfModelError('Unknown model: timeout-model',),).toBe('permanent',);
        // The recorded abort above, with a transient word after it: made up beyond that capture, and the boundary is the
        // terminal cause read before the word beside it.
        expect(kindOfModelError(`${OPERATION_ABORTED} after timed out`,),).toBe('permanent',);
      },
    },),
    it({
      name: 'reads a quota named without a status code apart, and a throttle named without a space too',
      fn: async () => {
        expect(kindOfModelError(QUOTA_NAMED_WITHOUT_STATUS,),).toBe('quota-reached',);
        // Made up, no program's output: a quota named in a JSON body, with an underscore and no status.
        expect(kindOfModelError('{"error":"quota_exceeded"}',),).toBe('quota-reached',);
        // Made up, no program's output: a throttle written as one word, with no space for the phrase to sit in.
        expect(kindOfModelError('RateLimitExceeded',),).toBe('throttled',);
        // A text Pi's own retry list holds, `@earendil-works/pi-ai/dist/utils/retry.js:32`.
        expect(kindOfModelError('server_busy',),).toBe('transient',);
        // Made up, no program's output: a dropped connection worded as the driver's own phrase list words it.
        expect(kindOfModelError('the connection was closed',),).toBe('transient',);
      },
    },),
    it({
      name: 'reads a status code hung on a number that is no status as no failure of its own',
      fn: async () => {
        // Made up, no program's output: a token count that holds a transient status inside a longer number.
        expect(kindOfModelError('the request held 15203 tokens',),).toBe('permanent',);
        // Made up, no program's output: a request number that holds a transient status inside a longer number.
        expect(kindOfModelError('retry 5203 later',),).toBe('permanent',);
        // A number later in the text is not the response's status, however much it looks like one: the provider's own limit is
        // a fixed configuration that a continuation prompt cannot change. Made up, no program's output: a refused status whose
        // body states a token limit of 500.
        expect(kindOfModelError('400 Bad Request: max_tokens must not exceed 500',),).toBe('permanent',);
        // The control: a status the text starts with does decide. Made up, no program's output: the reason phrase of one.
        expect(kindOfModelError('500 Internal Server Error',),).toBe('transient',);
        // Made up, no program's output: a status with nothing after it but a space.
        expect(kindOfModelError('520 ',),).toBe('transient',);
        // A status the text starts with decides whatever the body it explains says, so a request the provider refused is not
        // made again because its body mentions a transient failure. Made up, no program's output: a refused status whose body
        // names an internal error.
        expect(kindOfModelError('400 Bad Request: internal error while reading the request',),).toBe('permanent',);
        // Made up, no program's output: a transient status whose body names an internal error.
        expect(kindOfModelError('503 Service Unavailable: internal error while reading the request',),).toBe('transient',);
      },
    },),
    it({
      name: 'reads a status that asks for another attempt as transient, the timeouts included',
      fn: async () => {
        // Made up, no program's output: the reason phrase of each status below, none of them recorded by a run here; the
        // boundary is the code at the start of the text, the transient ones first and the refused one at the end.
        expect(kindOfModelError('408 Request Timeout',),).toBe('transient',);
        expect(kindOfModelError('522 Connection timed out',),).toBe('transient',);
        expect(kindOfModelError('425 Too Early',),).toBe('transient',);
        expect(kindOfModelError('521 Web Server Is Down',),).toBe('transient',);
        expect(kindOfModelError('523 Origin Is Unreachable',),).toBe('transient',);
        // The control: a status that refuses the request itself stays a failure no attempt can fix.
        expect(kindOfModelError('501 Not Implemented',),).toBe('permanent',);
        // The same made-up refused status as above, here beside the transient one it is read apart from.
        expect(kindOfModelError('400 Bad Request: max_tokens must not exceed 500',),).toBe('permanent',);
      },
    },),
    it({
      name: 'reads a status that refused the credentials before any word of its body',
      fn: async () => {
        // The body names a page about rate limits, which is no rate limit this attempt could wait out. Made up, no program's
        // output: a refused status whose body holds that page's address.
        expect(kindOfModelError('401 Unauthorized: Invalid API key. See /docs/rate-limits for details.',),)
          .toBe('permanent',);
        // Made up, no program's output: a refused status whose body names a throttle.
        expect(kindOfModelError('403 Forbidden: too many requests for this workspace',),).toBe('permanent',);
        // What the round before established: a rate limit that names an API key is still a rate limit. Made up, no program's
        // output: a 429 whose body names the key it limited.
        expect(kindOfModelError('429 Too many requests for this API key; retry_after=1',),).toBe('throttled',);
      },
    },),
    it({
      name: 'reads a rate limit that names what it limited as a rate limit, not as a bad credential',
      fn: async () => {
        // The same made-up 429 as above.
        expect(kindOfModelError('429 Too many requests for this API key; retry_after=1',),).toBe('throttled',);
        // Made up, no program's output: a throttle that names the API key it limited.
        expect(kindOfModelError('Rate limit reached for the API key of this workspace',),).toBe('throttled',);
        // A credential failure no rate limit names stays one another attempt cannot fix; made up as above.
        expect(kindOfModelError('Invalid API key for upstream provider',),).toBe('permanent',);
      },
    },),
  ],
},);

await describe({
  name: retryDelayMilliseconds.name,
  children: [
    it({
      name: 'doubles the first delay with each attempt',
      fn: async () => {
        const delays = [1, 2, 3,].map(function delayOf(retryNumber,) {
          return retryDelayMilliseconds({
            problem: REQUEST_TIMED_OUT,
            retryNumber,
            baseSeconds: MODEL_ERROR_RETRY_BASE_SECONDS,
          },);
        },);
        expect(delays,).toEqual([2_000, 4_000, 8_000,],);
      },
    },),
    it({
      name: 'waits as long as the provider asked, within the largest delay',
      fn: async () => {
        expect(waitAskedByProvider(CLOUDFLARE_520,),).toEqual({
          asked: true,
          milliseconds: 60_000,
        },);
        // Made up, no program's output: a wait written as the `Retry-After` header a response carries.
        expect(waitAskedByProvider('Retry-After: 30',),).toEqual({
          asked: true,
          milliseconds: 30_000,
        },);
        expect(waitAskedByProvider(REQUEST_TIMED_OUT,),).toEqual({ asked: false, },);
        expect(retryDelayMilliseconds({
          problem: CLOUDFLARE_520,
          retryNumber: 1,
          baseSeconds: MODEL_ERROR_RETRY_BASE_SECONDS,
        },),).toBe(MODEL_ERROR_RETRY_MAX_DELAY_MILLISECONDS,);
        // Made up, no program's output: the same header asking for a wait past the largest delay.
        expect(retryDelayMilliseconds({
          problem: 'Retry-After: 3600',
          retryNumber: 1,
          baseSeconds: MODEL_ERROR_RETRY_BASE_SECONDS,
        },),).toBe(MODEL_ERROR_RETRY_MAX_DELAY_MILLISECONDS,);
      },
    },),
    it({
      name: 'reads a wait written across a line break',
      fn: async () => {
        // A body pretty-printed over several lines is still JSON, and its wait is still the wait it asks for. Made up, no
        // program's output: a body broken across a line break under a status, and the same header wrapped across one.
        expect(waitAskedByProvider('503 {"retry_after":\n3600}',),).toEqual({
          asked: true,
          milliseconds: 3_600_000,
        },);
        expect(waitAskedByProvider('Retry-After:\r\n 30',),).toEqual({
          asked: true,
          milliseconds: 30_000,
        },);
        // The same made-up body as above, asking for a wait past the largest delay.
        expect(retryDelayMilliseconds({
          problem: '503 {"retry_after":\n3600}',
          retryNumber: 1,
          baseSeconds: MODEL_ERROR_RETRY_BASE_SECONDS,
        },),).toBe(MODEL_ERROR_RETRY_MAX_DELAY_MILLISECONDS,);
      },
    },),
    it({
      name: 'never grows past the largest delay',
      fn: async () => {
        expect(retryDelayMilliseconds({
          problem: REQUEST_TIMED_OUT,
          retryNumber: 60,
          baseSeconds: MODEL_ERROR_RETRY_BASE_SECONDS,
        },),).toBe(MODEL_ERROR_RETRY_MAX_DELAY_MILLISECONDS,);
      },
    },),
  ],
},);

