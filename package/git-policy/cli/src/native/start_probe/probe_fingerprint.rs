//! What:
//!  What the record pins about the machine and the build it ran on:
//!  the kernel's release,
//!  the loaded module's version,
//!  source version and build ID,
//!  the boot's identity,
//!  and the handler binary's own identity.
//! Why:
//!  A record whose fingerprint differs from the running kernel,
//!  module or boot is stale,
//!  and an add reads stale readiness as not current rather than running a
//!  second probe
//!  (`doc/planning/cli-git-zfs-start-probe-design.md`,
//!  "The result record and its fingerprint").
//!  No term is a rule:
//!  the module's release string is identity and reporting,
//!  as the project's answer of 2026-11-19 leaves it.
//!  The paths are the caller's to name,
//!  so no control reads this machine's kernel files.
//!
//! In TS you'd write (pseudocode):
//! ```ts
//! const fingerprint = ProbeFingerprint.read(livePaths()); // { kernel: '6.8.0-147-generic', module: '2.4.4-1', ... }
//! ```

use std::path::{Path, PathBuf};

/// The kernel's own release text,
/// which is what `uname --kernel-release` prints.
pub const KERNEL_RELEASE_PATH: &str = "/proc/sys/kernel/osrelease";
/// The loaded module's release string.
pub const MODULE_VERSION_PATH: &str = "/sys/module/zfs/version";
/// The loaded module's source version.
pub const MODULE_SRCVERSION_PATH: &str = "/sys/module/zfs/srcversion";
/// The loaded module's build ID note.
pub const MODULE_BUILD_ID_PATH: &str = "/sys/module/zfs/notes/.note.gnu.build-id";
/// This boot's identity,
/// regenerated by the kernel at every boot.
pub const BOOT_ID_PATH: &str = "/proc/sys/kernel/random/boot_id";
/// The running binary's own file,
/// which the kernel names for this process.
pub const HANDLER_PATH: &str = "/proc/self/exe";

/// The most bytes one fingerprint attribute is read as:
/// the sysfs page it is created as.
pub const ATTRIBUTE_BOUND: usize = 4_096;

/// What:
///  The six paths a fingerprint reads.
/// Why:
///   A control names fixture files in this shape,
///  so every read and every absence is exercised without this machine's
///  kernel.
///
/// In TS you'd write (pseudocode):
/// ```ts
/// type FingerprintPaths = { kernel: string; version: string; srcversion: string; buildId: string; bootId: string; handler: string };
/// ```
#[derive(Clone, Debug, Eq, PartialEq)]
pub struct FingerprintPaths {
    /// The kernel's release text.
    pub kernel_release: PathBuf,
    /// The module's release string.
    pub module_version: PathBuf,
    /// The module's source version.
    pub module_srcversion: PathBuf,
    /// The module's build ID note.
    pub module_build_id: PathBuf,
    /// This boot's identity.
    pub boot_id: PathBuf,
    /// The running binary's own file.
    pub handler: PathBuf,
}

impl FingerprintPaths {
    /// The paths a probe at boot reads.
    pub fn live() -> Self {
        return FingerprintPaths {
            kernel_release: PathBuf::from(KERNEL_RELEASE_PATH),
            module_version: PathBuf::from(MODULE_VERSION_PATH),
            module_srcversion: PathBuf::from(MODULE_SRCVERSION_PATH),
            module_build_id: PathBuf::from(MODULE_BUILD_ID_PATH),
            boot_id: PathBuf::from(BOOT_ID_PATH),
            handler: PathBuf::from(HANDLER_PATH),
        };
    }
}

/// What:
///  Why the fingerprint could not be read at all.
/// Why:
///  A record with no boot identity cannot be told from another boot's,
///  and a record with no kernel release cannot be told from another kernel's,
///  so those two are refusals;
///  the module's three attributes weaken the record instead,
///  as the gate's identity does.
///
/// In TS you'd write (pseudocode):
/// ```ts
/// type FingerprintRefusal = { kind: 'kernel' | 'boot'; path: string; reason: string };
/// ```
#[derive(Clone, Debug, Eq, PartialEq)]
pub enum FingerprintRefusal {
    /// The kernel's release text could not be read.
    KernelRelease {
        /// The path that was read.
        path: PathBuf,
        /// What the read answered.
        reason: String,
    },
    /// This boot's identity could not be read.
    BootId {
        /// The path that was read.
        path: PathBuf,
        /// What the read answered.
        reason: String,
    },
}

impl FingerprintRefusal {
    /// The refusal in words,
    /// naming the file and the way forward.
    pub fn message(&self) -> String {
        return match self {
            FingerprintRefusal::KernelRelease { path, reason } => format!(
                "the probe could not read the kernel's release from {} ({reason}), so no record can say which kernel it judged. Nothing was attached.",
                path.display()
            ),
            FingerprintRefusal::BootId { path, reason } => format!(
                "the probe could not read this boot's identity from {} ({reason}), so no record can say which boot it belongs to. Nothing was attached.",
                path.display()
            ),
        };
    }
}

/// What:
///  The five facts a record pins,
///  with the module's absent attributes kept absent rather than invented.
/// Why:
///  A module that carries no build ID weakens the staleness check,
///  never refuses,
///  and `doctor` says which attribute is absent.
///
/// In TS you'd write (pseudocode):
/// ```ts
/// type Fingerprint = { kernel: string; module?: string; srcversion?: string; buildId?: string; bootId: string; handler?: string };
/// ```
#[derive(Clone, Debug, Eq, PartialEq)]
pub struct ProbeFingerprint {
    /// The kernel's release text.
    pub kernel_release: String,
    /// The module's release string.
    pub module_version: Option<String>,
    /// The module's source version.
    pub module_srcversion: Option<String>,
    /// The module's build ID note,
    /// as lowercase hexadecimal.
    pub module_build_id: Option<String>,
    /// This boot's identity.
    pub boot_id: String,
    /// The running binary's own identity,
    /// in the shape the wrapper's cache records one.
    pub handler: Option<String>,
}

impl ProbeFingerprint {
    /// Read every fact from the given paths.
    ///
    /// # Errors
    /// The kernel's release or the boot's identity could not be read.
    pub fn read(paths: &FingerprintPaths) -> Result<Self, FingerprintRefusal> {
        let kernel_release: String = match read_text(paths.kernel_release.as_path()) {
            Ok(text) => text,
            Err(reason) => return Err(FingerprintRefusal::KernelRelease { path: paths.kernel_release.clone(), reason }),
        };
        let boot_id: String = match read_text(paths.boot_id.as_path()) {
            Ok(text) => text,
            Err(reason) => return Err(FingerprintRefusal::BootId { path: paths.boot_id.clone(), reason }),
        };
        return Ok(ProbeFingerprint {
            kernel_release,
            module_version: read_text(paths.module_version.as_path()).ok(),
            module_srcversion: read_text(paths.module_srcversion.as_path()).ok(),
            module_build_id: read_bytes(paths.module_build_id.as_path()).ok().map(|bytes| return hexadecimal(bytes.as_slice())),
            boot_id,
            handler: binary_identity(paths.handler.as_path()),
        });
    }
}

/// What:
///  One file's whole text,
///  bound to one page and stripped of one trailing newline.
/// Why:
///   The kernel's attribute files end in one newline,
///  and a record line cannot carry it.
///
/// In TS you'd write (pseudocode):
/// ```ts
/// const text = readText(path).replace(/\n$/, '');
/// ```
///
/// # Errors
/// The file could not be read or is longer than the bound.
pub fn read_text(path: &Path) -> Result<String, String> {
    let bytes: Vec<u8> = read_bytes(path)?;
    let text: String = String::from_utf8(bytes).map_err(|error| return error.to_string())?;
    return Ok(String::from(text.strip_suffix('\n').unwrap_or(text.as_str())));
}

/// What:
///  One file's whole bytes,
///  bound to one page.
/// Why:
///   A build ID is bytes and not text,
///  and a bound keeps a surprise file from filling the record.
///
/// In TS you'd write (pseudocode):
/// ```ts
/// const bytes = readBytes(path, 4096); // throws when the file is larger
/// ```
///
/// # Errors
/// The file could not be read or is longer than the bound.
pub fn read_bytes(path: &Path) -> Result<Vec<u8>, String> {
    use std::io::Read;
    let mut file: std::fs::File = std::fs::File::open(path).map_err(|error| return error.to_string())?;
    let mut bytes: Vec<u8> = Vec::new();
    let read: usize = file.by_ref().take((ATTRIBUTE_BOUND + 1) as u64).read_to_end(&mut bytes).map_err(|error| return error.to_string())?;
    if read > ATTRIBUTE_BOUND {
        return Err(format!("longer than {ATTRIBUTE_BOUND} bytes"));
    }
    return Ok(bytes);
}

/// The bytes as lowercase hexadecimal.
pub fn hexadecimal(bytes: &[u8]) -> String {
    let mut text: String = String::with_capacity(bytes.len() * 2);
    for byte in bytes {
        text.push_str(format!("{byte:02x}").as_str());
    }
    return text;
}

/// What:
///  The running binary's own identity:
///  its canonical path,
///  size,
///  times,
///  device and inode.
/// Why:
///   A rebuilt handler is a different build,
///  so a record it did not write reads as stale,
///  and the shape is the wrapper's cache's,
///  which records these six facts for the executable it starts.
///
/// In TS you'd write (pseudocode):
/// ```ts
/// const identity = identityOf('/proc/self/exe'); // 'path\tlen\tmtime.mtime_nsensec\tctime.ctime_nsec\tdev\tino'
/// ```
pub fn binary_identity(executable: &Path) -> Option<String> {
    use std::os::unix::fs::MetadataExt;
    let canonical: PathBuf = std::fs::canonicalize(executable).ok()?;
    let path: &str = canonical.to_str()?;
    if path.contains('\n') || path.contains('\t') || path.contains(' ') {
        return None;
    }
    let metadata: std::fs::Metadata = std::fs::metadata(canonical.as_path()).ok()?;
    if !metadata.is_file() {
        return None;
    }
    return Some(format!(
        "{path}\t{}\t{}.{}\t{}.{}\t{}\t{}",
        metadata.len(),
        metadata.mtime(),
        metadata.mtime_nsec(),
        metadata.ctime(),
        metadata.ctime_nsec(),
        metadata.dev(),
        metadata.ino()
    ));
}

