//! What:
//! The line-level YAML reader,
//! over the forms the generator writes,
//! the JavaScript
//!       trim cases that no longer apply,
//! and every form it refuses.
//! Why:
//! A line read wrongly is a nesting read wrongly,
//! and a refused line is the only way
//!      this reader says it cannot tell a publish set from another list.
//!
//! In TS you'd write (pseudocode):
//! ```ts
//! // expect(readScalar("'@s/a'")).toBe('@s/a');
//! ```

/// The line-level reader under test.
use super::{
    YamlLine, YamlProblem, is_item, item_content, read_lines, read_scalar, split_key,
};

/// The lines of a text that carries content.
fn lines(text: &str) -> Vec<YamlLine<'_>> {
    return read_lines(text).unwrap_or_else(|problem: YamlProblem| panic!("{problem:?}"));
}

/// Blank lines and comments carry no structure;
/// indentation is counted in spaces;
/// a
///       carriage return is not part of the content.
#[test]
fn reads_only_the_lines_that_carry_structure() {
    assert_eq!(
        lines("# Generated by the generator\r\n\r\nauth:   \r\n  oidc:\r\n"),
        vec![
            YamlLine {
                number: 3,
                indent: 0,
                content: "auth:",
            },
            YamlLine {
                number: 4,
                indent: 2,
                content: "oidc:",
            },
        ]
    );
    assert_eq!(lines(""), Vec::<YamlLine<'_>>::new());
    assert_eq!(lines("\n\n# only a comment\n"), Vec::<YamlLine<'_>>::new());
}

/// A tab indents nothing,
/// and a document marker is a second document this reader does not
///       read.
#[test]
fn refuses_a_tab_and_a_document_marker() {
    assert_eq!(
        read_lines("auth:\n\toidc:\n"),
        Err(YamlProblem::new(
            2,
            "is indented with a tab, which starts no block"
        ))
    );
    assert_eq!(
        read_lines("---\nauth:\n"),
        Err(YamlProblem::new(
            1,
            "marks a document boundary, and this reader reads one document"
        ))
    );
}

/// A dash opens an item only with the one space the generator writes,
/// or nothing after it.
#[test]
fn tells_an_item_from_a_scalar_that_begins_with_a_dash() {
    assert!(is_item("-"));
    assert!(is_item("- '@s/a'"));
    assert!(!is_item("-1"));
    assert!(!is_item("'- a'"));
    assert_eq!(item_content("- '@s/a'"), "'@s/a'");
    assert_eq!(item_content("-"), "");
    // A wider gap and a tab are not items this reader reads; `read_lines` refuses them.
    assert!(!is_item("-   spaced"));
    assert!(!is_item("-\tapp"));
    assert!(!is_item("- \tapp"));
}

/// A key ends at a colon a space or the line end follows,
/// and a quoted key is one
///       key even when it holds colons.
#[test]
fn splits_a_key_from_its_scalar() {
    assert_eq!(
        split_key("packages:"),
        Ok(Some((String::from("packages"), "")))
    );
    assert_eq!(
        split_key("registry: monochromatic-dev"),
        Ok(Some((String::from("registry"), "monochromatic-dev")))
    );
    assert_eq!(
        split_key("registry : monochromatic-dev"),
        Ok(Some((String::from("registry"), "monochromatic-dev")))
    );
    assert_eq!(
        split_key("'@monochromatic-dev/*':"),
        Ok(Some((String::from("@monochromatic-dev/*"), "")))
    );
    assert_eq!(
        split_key("'repo:example/main': x"),
        Ok(Some((String::from("repo:example/main"), "x")))
    );
    assert_eq!(split_key("- '@s/a'"), Ok(None));
    assert_eq!(split_key("no colon here"), Ok(None));
    assert_eq!(split_key("not:a:key"), Ok(None));
}

/// A key this reader would have to guess at is refused,
/// never stored under the
///       text it happens to hold:
/// a tag,
/// anchor,
/// alias or block indicator
///       means the entry has another name,
/// and an empty key names nothing.
#[test]
fn refuses_keys_it_does_not_read() {
    assert_eq!(
        split_key("!!str packages:"),
        Err(String::from(
            "begins with '!', which opens a key this reader does not read"
        ))
    );
    assert_eq!(
        split_key("&anchor packages:"),
        Err(String::from(
            "begins with '&', which opens a key this reader does not read"
        ))
    );
    assert_eq!(
        split_key("*alias:"),
        Err(String::from(
            "begins with '*', which opens a key this reader does not read"
        ))
    );
    assert_eq!(
        split_key("|block:"),
        Err(String::from(
            "begins with '|', which opens a key this reader does not read"
        ))
    );
    assert_eq!(
        split_key("? packages:"),
        Err(String::from(
            "begins with '?', which opens a key this reader does not read"
        ))
    );
    assert_eq!(split_key(":"), Err(String::from("names no key")));
    assert_eq!(split_key("'':"), Err(String::from("names no key")));
    assert_eq!(split_key("-x: 1"), Ok(Some((String::from("-x"), "1"))));
    assert_eq!(
        split_key("'a':b"),
        Err(String::from(
            "puts its colon against its value, which this reader does not read"
        ))
    );
}

/// Single quotes escape by doubling,
/// double quotes read two escapes,
/// a plain scalar
///       ends at a comment,
/// and everything else is refused.
#[test]
fn reads_and_refuses_scalars() {
    assert_eq!(read_scalar("'@s/a'"), Ok(String::from("@s/a")));
    assert_eq!(read_scalar("'it''s'"), Ok(String::from("it's")));
    assert_eq!(read_scalar("'@s/a'  # one"), Ok(String::from("@s/a")));
    assert_eq!(read_scalar("\"a\\\\b\\\"c\""), Ok(String::from("a\\b\"c")));
    assert_eq!(read_scalar("${PNPR_SECRET}"), Ok(String::from("${PNPR_SECRET}")));
    assert_eq!(read_scalar("https://pnpr.example"), Ok(String::from("https://pnpr.example")));
    assert_eq!(read_scalar("$all  # everyone"), Ok(String::from("$all")));
    assert_eq!(read_scalar(""), Ok(String::new()));
    assert_eq!(
        read_scalar("'@s/a' x"),
        Err(String::from("holds text after its closing quote"))
    );
    assert_eq!(
        read_scalar("'@s/a"),
        Err(String::from("opens a quote that never closes"))
    );
    assert_eq!(
        read_scalar("\"a\\nb\""),
        Err(String::from(
            "uses the escape \\n, which this reader does not read"
        ))
    );
    assert_eq!(
        read_scalar("[a, b]"),
        Err(String::from(
            "begins with '[', which opens a value this reader does not read"
        ))
    );
    assert_eq!(
        read_scalar("*anchor"),
        Err(String::from(
            "begins with '*', which opens a value this reader does not read"
        ))
    );
    assert_eq!(
        read_scalar("repo: example"),
        Err(String::from(
            "holds a colon a space or tab follows, so it reads as a key and not as one value"
        ))
    );
    assert_eq!(
        read_scalar("trailing:"),
        Err(String::from(
            "holds a colon a space or tab follows, so it reads as a key and not as one value"
        ))
    );
}

/// A tab separates as a space does,
/// and every other form this reader would have to guess
///       at is refused:
/// a comment after a plain scalar,
/// a tab before the comment,
/// a
///       mapping colon,
/// a comment or an item indicator where a value belongs,
/// text after a
///       closing quote with no space before it,
/// and a carriage return inside a line.
#[test]
fn reads_a_tab_and_refuses_every_form_it_does_not_read() {
    assert_eq!(read_scalar("app\t# published"), Ok(String::from("app")));
    assert_eq!(read_scalar("app\t"), Ok(String::from("app")));
    assert_eq!(read_scalar("app\tb"), Ok(String::from("app\tb")));
    assert_eq!(
        read_lines("a:\n  - \tapp\n"),
        Err(YamlProblem::new(
            2,
            "puts a tab after the space that follows its dash, which this reader does not read"
        ))
    );
    assert_eq!(
        read_scalar("repo:\texample"),
        Err(String::from(
            "holds a colon a space or tab follows, so it reads as a key and not as one value"
        ))
    );
    assert_eq!(
        read_scalar("# published"),
        Err(String::from(
            "begins with '#', which opens a value this reader does not read"
        ))
    );
    assert_eq!(
        read_scalar("- item"),
        Err(String::from(
            "begins with '-', which opens a value this reader does not read"
        ))
    );
    assert_eq!(
        read_scalar("? key"),
        Err(String::from(
            "begins with '?', which opens a value this reader does not read"
        ))
    );
    assert_eq!(
        read_scalar("'app'#published"),
        Err(String::from("holds text after its closing quote"))
    );
    assert_eq!(
        read_lines("auth:\roidc:\n"),
        Err(YamlProblem::new(
            1,
            "holds a carriage return, which starts a new line"
        ))
    );
}
