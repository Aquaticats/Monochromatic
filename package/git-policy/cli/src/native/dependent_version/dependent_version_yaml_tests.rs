//! What:
//! The block reader,
//! over the shape the generator writes and every form it refuses.
//! Why:
//! The publish set is four levels down,
//! so the nesting is what a line scan could not
//!      see;
//! each refusal here is a text the policy reports instead of reading a guess.
//!
//! In TS you'd write (pseudocode):
//! ```ts
//! // expect(parseYamlDocument('a:\n  - b\n')).toEqual(new Map([['a', ['b']]]));
//! ```

/// The block reader and its node kind under test.
use super::{YamlNode, parse_yaml_document};
/// The problem type and the line reader the blocks build on.
use crate::dependent_version_yaml_lines::YamlProblem;

/// A tree of mappings and sequences,
/// written the way the reader builds one.
fn mapping(entries: Vec<(&str, YamlNode)>) -> YamlNode {
    return YamlNode::Mapping(
        entries
            .iter()
            .map(|entry: &(&str, YamlNode)| {
                return (String::from(entry.0), entry.1.clone());
            })
            .collect(),
    );
}

/// A sequence of scalar items.
fn scalars(items: &[&str]) -> YamlNode {
    return YamlNode::Sequence(
        items
            .iter()
            .map(|item: &&str| return YamlNode::Scalar(String::from(*item)))
            .collect(),
    );
}

/// The document of a text this reader reads.
fn document(text: &str) -> YamlNode {
    return parse_yaml_document(text).unwrap_or_else(|problem: YamlProblem| panic!("{problem:?}"));
}

/// The problem of a text this reader refuses.
fn problem(text: &str) -> YamlProblem {
    return parse_yaml_document(text)
        .err()
        .unwrap_or_else(|| panic!("expected a problem for {text:?}"));
}

/// A key line and the deeper lines below it are one entry;
/// a deeper dash list is one
///       sequence,
/// and a comment or blank line changes nothing.
#[test]
fn reads_nesting_from_indentation() {
    assert_eq!(
        document("# a comment\na: 1\nb:\n  - 'x'\n  - 'y'\nc:\n    d: true\n"),
        mapping(vec![
            ("a", YamlNode::Scalar(String::from("1"))),
            ("b", scalars(&["x", "y"])),
            (
                "c",
                mapping(vec![("d", YamlNode::Scalar(String::from("true")))])
            ),
        ])
    );
    assert_eq!(document(""), YamlNode::Mapping(Vec::new()));
    assert_eq!(document("# nothing but a comment\n"), YamlNode::Mapping(Vec::new()));
}

/// An item holds a scalar,
/// a compact mapping whose later keys line up under its first,
/// or
///       a block on the lines below a lone dash.
#[test]
fn reads_the_three_shapes_of_an_item() {
    assert_eq!(
        document("list:\n  - 'a'\n  - k: 1\n    m:\n      - 2\n  - \n"),
        mapping(vec![(
            "list",
            YamlNode::Sequence(vec![
                YamlNode::Scalar(String::from("a")),
                mapping(vec![
                    ("k", YamlNode::Scalar(String::from("1"))),
                    ("m", scalars(&["2"])),
                ]),
                YamlNode::Scalar(String::new()),
            ])
        )])
    );
}

/// The generated configuration's own shape:
/// providers,
/// workloads,
/// the identity mapping
///       above the package list,
/// and a quoted registry key below it.
#[test]
fn reads_the_generated_configuration() {
    let text: &str = concat!(
        "# Generated by @monochromatic-dev/config-pnpr\n",
        "auth:\n",
        "  oidc:\n",
        "    - name: github\n",
        "      workloads:\n",
        "        - identity:\n",
        "            subject: 'repo:example/main'\n",
        "          registry: monochromatic-dev\n",
        "          packages:\n",
        "            - '@s/a'\n",
        "\n",
        "registries:\n",
        "  monochromatic-dev:\n",
        "    packages:\n",
        "      '@monochromatic-dev/*':\n",
        "        access: $all\n",
    );
    let read: YamlNode = document(text);
    let providers: &[YamlNode] = read
        .entry("auth")
        .and_then(|auth: &YamlNode| return auth.entry("oidc"))
        .and_then(YamlNode::items)
        .unwrap_or_else(|| panic!("no providers"));
    assert_eq!(providers.len(), 1);
    let workload: &YamlNode = &providers[0]
        .entry("workloads")
        .and_then(YamlNode::items)
        .unwrap_or_else(|| panic!("no workloads"))[0];
    assert_eq!(
        workload.entry("packages"),
        Some(&scalars(&["@s/a"]))
    );
    assert_eq!(
        workload
            .entry("identity")
            .and_then(|identity: &YamlNode| return identity.entry("subject"))
            .and_then(YamlNode::text),
        Some("repo:example/main")
    );
    assert_eq!(
        read.entry("registries")
            .and_then(|registries: &YamlNode| return registries.entry("monochromatic-dev"))
            .and_then(|registry: &YamlNode| return registry.entry("packages"))
            .and_then(|packages: &YamlNode| return packages.entry("@monochromatic-dev/*"))
            .and_then(|pattern: &YamlNode| return pattern.entry("access"))
            .and_then(YamlNode::text),
        Some("$all")
    );
}

/// A node of another kind answers no,
/// so a wrong shape becomes a diagnostic rather than a
///       panic.
#[test]
fn answers_no_for_the_wrong_kind() {
    let node: YamlNode = scalars(&["a"]);
    assert_eq!(node.entry("a"), None);
    assert_eq!(node.text(), None);
    assert_eq!(
        YamlNode::Scalar(String::from("a")).items(),
        None,
        "a scalar holds no items"
    );
    assert_eq!(
        YamlNode::Scalar(String::from("a")).text(),
        Some("a"),
        "a scalar holds its text"
    );
}

/// A document that starts indented,
/// a line deeper than the block above it,
/// a dash where
///       a key belongs,
/// and a repeated key are each refused by line.
#[test]
fn refuses_what_it_cannot_place() {
    assert_eq!(
        problem("  a: 1\n"),
        YamlProblem::new(1, "starts the document indented, where no block can open")
    );
    assert_eq!(
        problem("a: 1\n   b: 2\n"),
        YamlProblem::new(2, "is indented deeper than the block it follows")
    );
    assert_eq!(
        problem("a: 1\n  - b\n"),
        YamlProblem::new(2, "is indented deeper than the block it follows")
    );
    assert_eq!(
        problem("a:\n  - b\n    c: 1\n"),
        YamlProblem::new(3, "is indented deeper than the block it follows")
    );
    assert_eq!(
        problem("a:\n  - b\n    - c\n"),
        YamlProblem::new(3, "is indented deeper than the block it follows")
    );
    assert_eq!(
        problem("a:\n  b: 1\n  - c\n"),
        YamlProblem::new(3, "opens a list item where a key was expected")
    );
    assert_eq!(
        problem("a: 1\nno key\n"),
        YamlProblem::new(2, "holds no key and colon")
    );
    assert_eq!(
        problem("a: 1\nb: 2\na: 3\n"),
        YamlProblem::new(3, "names the key \"a\" a second time")
    );
    assert_eq!(
        problem("a: [1, 2]\n"),
        YamlProblem::new(
            1,
            "begins with '[', which opens a value this reader does not read"
        )
    );
    assert_eq!(
        problem("a: |\n  text\n"),
        YamlProblem::new(
            1,
            "begins with '|', which opens a value this reader does not read"
        )
    );
    assert_eq!(
        problem("a:\n  b: 'x\n"),
        YamlProblem::new(2, "opens a quote that never closes")
    );
}

/// A tagged key is refused at its line:
/// `!!str packages:` names the entry `packages` to a YAML parser,
/// so the reader
///       must not keep the tag in the name and answer "no such entry".
#[test]
fn refuses_a_tagged_key_by_line() {
    assert_eq!(
        problem("a:\n  !!str packages:\n    - b\n"),
        YamlProblem::new(
            2,
            "begins with '!', which opens a key this reader does not read"
        )
    );
    assert_eq!(
        problem("a:\n  - !!str packages:\n      - b\n"),
        YamlProblem::new(
            2,
            "begins with '!', which opens a key this reader does not read"
        )
    );
}
