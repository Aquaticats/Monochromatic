#!/usr/bin/env node
// Lifecycle check of the headless Language module against real servers on disposable projects:
// open, one request, close, and the worker's shutdown, with every record the application logged
// captured. helix-lsp forwards each line a server writes to standard error into that log, so the
// capture holds the servers' standard error too. The log goes through the application's pipeline,
// which re-labels helix-lsp's records for healthy servers (src/logging/relabel.rs); every helix-lsp
// record is made visible here, so the re-labelled ones are checked for, not only their absence at ERROR.
// Part 1 (quiet shutdown): no ERROR-level record, no shutdown error text at WARN or ERROR or outside a
// record, helix-lsp's healthy-server records kept whole below WARN, no process left.
// Part 2 (abrupt end): SIGKILL of the application process leaves no server and no sandbox process.
// Servers run with the production launch policy, confined by bubblewrap.
// No server is ever pointed at this repository; it is read only to copy the TypeScript 7 packages.
import { spawn, spawnSync } from 'node:child_process';
import { cpSync, existsSync, mkdirSync, mkdtempSync, readFileSync, readdirSync, readlinkSync, realpathSync, statSync, writeFileSync } from 'node:fs';
import { homedir } from 'node:os';
import { join, resolve } from 'node:path';
import { setTimeout as wait } from 'node:timers/promises';

const binary = resolve('target/debug/ide-language-inspect');
const store = resolve('../../../node_modules/.pnpm');
// The private agent scratch root, on the same file system as real projects.
const privateRoot = join(homedir(), 'temp', 'agent');
if ((statSync(privateRoot).mode & 0o077) !== 0) throw new Error('Scratch root must exclude group and other permissions: ' + privateRoot);
const base = realpathSync(mkdtempSync(join(privateRoot, 'ide-language-lifecycle-')));
const results = join(base, 'results');
mkdirSync(results);
console.log('LANGUAGE_LIFECYCLE_ARTIFACT=' + base);

// region fixtures
const write = ({ root, relative, text }: { root: string; relative: string; text: string }): void => {
  const target = join(root, relative);
  mkdirSync(join(target, '..'), { recursive: true });
  writeFileSync(target, text);
};
// Character offset (Unicode scalar values, as the application counts) of `needle` plus `within` characters.
const offsetOf = ({ text, needle, within = 0 }: { text: string; needle: string; within?: number }): number => {
  const index = text.indexOf(needle);
  if (index < 0) throw new Error('fixture text lacks ' + needle);
  return [...text.slice(0, index)].length + within;
};
const ts = join(base, 'ts-project');
write({ root: ts, relative: 'package.json', text: JSON.stringify({ name: 'lifecycle-ts', private: true, type: 'module' }, null, 2) + '\n' });
write({ root: ts, relative: 'tsconfig.json', text: JSON.stringify({ compilerOptions: { target: 'es2022', module: 'esnext', moduleResolution: 'bundler', strict: true, noEmit: true }, include: ['src'] }, null, 2) + '\n' });
write({ root: ts, relative: 'src/greet.ts', text: ['/** Build a greeting for one name. */', 'export function greet(name: string): string {', '  return `hello ${name}`;', '}', ''].join('\n') });
const tsMain = ['import { greet } from "./greet";', '', 'const message = greet("world");', 'console.log(message);', ''].join('\n');
write({ root: ts, relative: 'src/main.ts', text: tsMain });
cpSync(join(store, 'typescript@7.0.2', 'node_modules', 'typescript'), join(ts, 'node_modules', 'typescript'), { recursive: true });
cpSync(
  join(store, '@typescript+typescript-linux-x64@7.0.2', 'node_modules', '@typescript', 'typescript-linux-x64'),
  join(ts, 'node_modules', '@typescript', 'typescript-linux-x64'),
  { recursive: true },
);
const rust = join(base, 'rust-project');
write({ root: rust, relative: 'Cargo.toml', text: ['[package]', 'name = "lifecycle-rust"', 'version = "0.1.0"', 'edition = "2024"', '', '[workspace]', ''].join('\n') });
// A committed lockfile, as real projects have: confined, cargo cannot write one into the read-only project.
write({ root: rust, relative: 'Cargo.lock', text: ['# This file is automatically @generated by Cargo.', '# It is not intended for manual editing.', 'version = 4', '', '[[package]]', 'name = "lifecycle-rust"', 'version = "0.1.0"', ''].join('\n') });
write({ root: rust, relative: 'src/shape.rs', text: ['/// Multiply width by height.', 'pub fn area(width: u32, height: u32) -> u32 {', '    width * height', '}', ''].join('\n') });
const rustMain = ['mod shape;', '', 'fn main() {', '    let total = shape::area(2, 3);', '    println!("{total}");', '}', ''].join('\n');
write({ root: rust, relative: 'src/main.rs', text: rustMain });
// endregion

// region observation helpers
// Every process, as { pid, parent, start, name }. The start time tells a reused process number from the original.
interface ProcessInfo { pid: number; parent: number; start: string | undefined; name: string }
const processes = (): ProcessInfo[] => readdirSync('/proc').filter(name => /^\d+$/.test(name)).flatMap(pid => {
  try {
    const stat = readFileSync(join('/proc', pid, 'stat'), 'utf8');
    // The command name is in parentheses and may contain spaces; fields follow the last `)`.
    const fields = stat.slice(stat.lastIndexOf(')') + 2).split(' ');
    return [{ pid: Number(pid), parent: Number(fields[1]), start: fields[19], name: stat.slice(stat.indexOf('(') + 1, stat.lastIndexOf(')')) }];
  } catch { return []; }
});
// Every descendant of `root`, found before the application process is ended.
const descendants = (root: number | undefined): ProcessInfo[] => {
  const all = processes();
  const found: ProcessInfo[] = [];
  let frontier: (number | undefined)[] = [root];
  while (frontier.length > 0) {
    const next = all.filter(item => frontier.includes(item.parent));
    found.push(...next);
    frontier = next.map(item => item.pid);
  }
  return found;
};
// Which of the recorded processes still exist (same process number and same start time).
const surviving = (recorded: ProcessInfo[]): ProcessInfo[] => {
  const now = processes();
  return recorded.filter(item => now.some(current => current.pid === item.pid && current.start === item.start));
};
// Processes carrying the session marker in their environment, or working inside the fixture.
const marked = (marker: string): string[] => readdirSync('/proc').filter(name => /^\d+$/.test(name)).flatMap(pid => {
  let found = false;
  try { found = readFileSync(join('/proc', pid, 'environ'), 'latin1').includes('IDE_LANGUAGE_SESSION=' + marker); } catch { /* another user's process, or it ended */ }
  try { found ||= readlinkSync(join('/proc', pid, 'cwd')).startsWith(base); } catch { /* as above */ }
  try { return found ? [pid + ' ' + readFileSync(join('/proc', pid, 'comm'), 'utf8').trim()] : []; } catch { return []; }
});
// One record of the application log per line; ANSI color sequences removed.
const logRecords = (text: string): string[] => text.replaceAll(/\u001b\[[0-9;]*m/g, '').split('\n').filter(Boolean);
const levelOf = (line: string): string | undefined => /^\S+\s+(TRACE|DEBUG|INFO|WARN|ERROR)\s/.exec(line)?.[1];
// Text a process prints when it reports its own shutdown as a failure. It is a bare shutdown error
// when it reaches the log at WARN or ERROR, or outside any record; below WARN it is labelled for what it is.
const bareShutdownError = /context canceled|StreamClosed|broken pipe/i;
const bareLevels = new Set<string | undefined>(['WARN', 'ERROR', undefined]);
// The three helix-lsp record shapes for a healthy server, worded as helix-lsp words them.
const helixShapes: [string, RegExp][] = [
  ['server standard error line', /helix_lsp::transport: \S+ err <- ".*"$/],
  ['end of server standard error', /helix_lsp::transport: \S+ err: <- StreamClosed$/],
  ['moot error answer', /helix_lsp::transport: \S+ <- ServerError\(-3280[01]\): /],
];
const tomlTable = (variables: Record<string, string>): string => '{ ' + Object.entries(variables).map(([name, value]) => name + ' = ' + JSON.stringify(value)).join(', ') + ' }';
// endregion

// The application's private state, which holds each server's cargo and cache redirects, goes below the fixture.
// RUST_LOG adds every helix-lsp record, protocol messages included, to the worker's debug records.
const environment: NodeJS.ProcessEnv = { ...process.env, XDG_CACHE_HOME: join(base, 'app-cache'), RUST_LOG: 'ide_app=debug,helix_lsp=debug' };
delete environment.CARGO_TARGET_DIR;
delete environment.CARGO_BUILD_BUILD_DIR;
interface LifecycleCase {
  name: string;
  server: string;
  project: string;
  file: string;
  at: number;
  warm: number;
  hover: string;
  definition: (marker: string) => string;
}
const cases: LifecycleCase[] = [
  { name: 'typescript', server: 'typescript-native', project: ts, file: 'src/main.ts', at: offsetOf({ text: tsMain, needle: 'greet("world")', within: 1 }), warm: 60, hover: 'greet',
    definition: (marker: string) => '[language-server.typescript-native]\ncommand = "node_modules/typescript/bin/tsc"\nenvironment = ' + tomlTable({ IDE_LANGUAGE_SESSION: marker }) + '\n' },
  { name: 'rust', server: 'rust-analyzer', project: rust, file: 'src/main.rs', at: offsetOf({ text: rustMain, needle: 'area(2, 3)', within: 1 }), warm: 120, hover: 'area',
    definition: (marker: string) => '[language-server.rust-analyzer]\nenvironment = ' + tomlTable({ IDE_LANGUAGE_SESSION: marker }) + '\n' },
];
const summary: { base: string; cases: unknown[] } = { base, cases: [] };
let failed = false;
const record = ({ name, checks, extra = {} }: { name: string; checks: [string, boolean][]; extra?: Record<string, unknown> }): void => {
  summary.cases.push({ name, checks: checks.map(([check, passed]) => ({ check, passed })), ...extra });
  for (const [check, passed] of checks) {
    if (!passed) failed = true;
    console.log((passed ? 'PASS ' : 'FAIL ') + name + ': ' + check);
  }
  writeFileSync(join(results, 'results.json'), JSON.stringify(summary, null, 2));
};

// region part 1: open, one request, close, and the worker's own shutdown.
// The records of the inspection binary's event stream, one JSON object per line; only the fields read here are named.
interface LifecycleEvent {
  step?: unknown;
  result?: { matched?: boolean };
  reply?: { outcome: { text?: string } };
}
for (const item of cases) {
  const marker = 'quiet-' + item.name + '-' + process.pid;
  const plan = { project: item.project, extra_languages: item.definition(marker), steps: [
    { label: 'open', do: 'open', file: item.file },
    { label: 'ready', do: 'ready', seconds: item.warm },
    { label: 'hover', do: 'request', kind: 'hover', at: item.at, until: 'hover', seconds: item.warm },
    { label: 'close', do: 'close' },
  ] };
  const planPath = join(results, item.name + '.quiet.plan.json');
  writeFileSync(planPath, JSON.stringify(plan, null, 2));
  const run = spawnSync(binary, [planPath], { encoding: 'utf8', env: environment, maxBuffer: 64 * 1024 * 1024 });
  writeFileSync(join(results, item.name + '.quiet.events.jsonl'), run.stdout ?? '');
  writeFileSync(join(results, item.name + '.quiet.log.txt'), run.stderr ?? '');
  if (run.error) throw run.error;
  const events = (run.stdout ?? '').split('\n').filter(Boolean).map((line): LifecycleEvent => JSON.parse(line));
  const steps = events.filter(event => event.step !== undefined);
  const hoverText = events.flatMap(event => (event.reply ? [event.reply.outcome.text ?? ''] : [])).join('\n');
  const lines = logRecords(run.stderr ?? '');
  const errors = lines.filter(line => levelOf(line) === 'ERROR');
  const bare = lines.filter(line => bareShutdownError.test(line) && bareLevels.has(levelOf(line)));
  // Each re-labelled record with its level; one at WARN or ERROR fails, as any ERROR record does.
  const relabelled = lines.flatMap(line => helixShapes.filter(([, pattern]) => pattern.test(line)).map(([shape]) => ({ shape, level: levelOf(line), line })));
  const loud = relabelled.filter(entry => !(['INFO', 'DEBUG'] as (string | undefined)[]).includes(entry.level));
  const shapes = Object.fromEntries(helixShapes.map(([shape]) => [shape, relabelled.filter(entry => entry.shape === shape).map(entry => entry.level)]));
  const state = join(base, 'app-cache', 'monochromatic-ide', 'language');
  const confined = existsSync(state) && readdirSync(state, { recursive: true, encoding: 'utf8' }).some(path => path.endsWith(item.server));
  const left = marked(marker);
  record({ name: item.name + ' quiet shutdown', checks: [
    ['the application process exited with status 0', run.status === 0],
    ['every step was recorded', steps.length === plan.steps.length],
    ['hover names the called function', steps[2]?.result?.matched === true && hoverText.includes(item.hover)],
    ['the server ran with private sandbox state', confined],
    ['the log has no ERROR-level record (' + errors.length + ' found)', errors.length === 0],
    ['the log has no bare shutdown error (' + bare.length + ' found)', bare.length === 0],
    ['helix-lsp\'s healthy-server records are in the log below WARN (' + relabelled.length + ' found, ' + loud.length + ' at WARN or above)', relabelled.length > 0 && loud.length === 0],
    ['no server or sandbox process is left', left.length === 0],
  ], extra: { errors, bare, warnings: lines.filter(line => levelOf(line) === 'WARN'), left, records: lines.length, shapes, relabelled: relabelled.map(entry => entry.line.slice(0, 300)) } });
  for (const line of new Set([...errors, ...bare, ...loud.map(entry => entry.line)])) console.log('     ' + line.slice(0, 300));
  console.log('     helix-lsp healthy-server records by shape, with their levels: ' + JSON.stringify(shapes));
}
// endregion

// region part 2: SIGKILL of the application process while a server is ready and has answered.
for (const item of cases) {
  const marker = 'killed-' + item.name + '-' + process.pid;
  const plan = { project: item.project, extra_languages: item.definition(marker), steps: [
    { label: 'open', do: 'open', file: item.file },
    { label: 'ready', do: 'ready', seconds: item.warm },
    { label: 'hover', do: 'request', kind: 'hover', at: item.at, until: 'hover', seconds: item.warm },
    // The application process is ended from outside during this step.
    { label: 'idle', do: 'sleep', milliseconds: 600000 },
  ] };
  const planPath = join(results, item.name + '.killed.plan.json');
  writeFileSync(planPath, JSON.stringify(plan, null, 2));
  const child = spawn(binary, [planPath], { env: environment, stdio: ['ignore', 'pipe', 'pipe'] });
  let output = '';
  let log = '';
  child.stdout.on('data', chunk => { output += chunk; });
  child.stderr.on('data', chunk => { log += chunk; });
  const ended = new Promise<{ code: number | null; signal: NodeJS.Signals | null }>(done => child.on('exit', (code, signal) => done({ code, signal })));
  const answered = () => output.split('\n').filter(Boolean).some(line => { try { const event = JSON.parse(line); return event.step === 2 && event.result.matched === true; } catch { return false; } });
  const deadline = Date.now() + (item.warm * 2 + 30) * 1000;
  while (!answered() && child.exitCode === null && Date.now() < deadline) await wait(100);
  const hoverAnswered = answered();
  // Let background work that follows the first answer (cargo check, project loading) get under way.
  await wait(2000);
  const before = descendants(child.pid);
  const markedBefore = marked(marker);
  child.kill('SIGKILL');
  const outcome = await ended;
  const ticks: { second: number; descendants: string[]; marked: string[] }[] = [];
  const started = Date.now();
  for (const second of [0, 1, 5, 10]) {
    await wait(Math.max(0, second * 1000 - (Date.now() - started)));
    ticks.push({ second, descendants: surviving(before).map(entry => entry.pid + ' ' + entry.name), marked: marked(marker) });
  }
  writeFileSync(join(results, item.name + '.killed.events.jsonl'), output);
  writeFileSync(join(results, item.name + '.killed.log.txt'), log);
  const last = ticks.at(-1);
  if (last === undefined) throw new Error('No tick was recorded after the application was ended');
  const firstEmpty = ticks.find(tick => tick.descendants.length === 0 && tick.marked.length === 0)?.second;
  record({ name: item.name + ' SIGKILL of the application', checks: [
    ['the server answered a hover before the application was ended', hoverAnswered],
    ['the application was ended by SIGKILL', outcome.signal === 'SIGKILL'],
    ['a bubblewrap process and a server process were running', before.some(entry => entry.name === 'bwrap') && before.length >= 2 && markedBefore.length > 0],
    ['no descendant of the application is left after 10 s', last.descendants.length === 0],
    ['no process with the session marker or inside the fixture is left after 10 s', last.marked.length === 0],
  ], extra: { before: before.map(entry => entry.pid + ' ' + entry.name + ' parent ' + entry.parent), markedBefore, ticks, firstEmptySecond: firstEmpty } });
  console.log('     processes before: ' + before.map(entry => entry.name).join(', ') + '; first empty tick: ' + (firstEmpty ?? 'none') + ' s');
}
// endregion

writeFileSync(join(results, 'results.json'), JSON.stringify(summary, null, 2));
console.log('Language lifecycle ' + (failed ? 'FAILED' : 'passed') + ': ' + join(results, 'results.json'));
if (failed) process.exitCode = 1;
