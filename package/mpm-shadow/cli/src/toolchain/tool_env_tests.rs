//! Unit tests of the tool environment fragment:
//! what is written for a lock's `env` blocks,
//! what a removed entry leaves behind,
//! and which values and names are refused or encoded because mise would misread them.
//! Every test works in a disposable scope and home.

use std::fs;
use std::path::{Path, PathBuf};

use super::context::Host;
use super::error::ErrorKind;
use super::fakes::Rig;
use super::model::{OsFamily, Request, expand_version};
use super::scope::{EnvMap, global_scope};
use super::sync::sync_tools;
use super::tool_env::write_tool_env;

/// Sets the `env` block of the locked tool `id` to `pairs`.
fn set_env(rig: &mut Rig, id: &str, pairs: &[(&str, &str)]) {
    for tool in &mut rig.lock.tools {
        if tool.declaration.id == id {
            tool.declaration.env = pairs.iter().map(|(name, value)| return (name.to_string(), value.to_string())).collect();
        }
    }
}

/// The repository scope's fragment path.
fn fragment_path(rig: &Rig) -> &Path {
    return rig.scope.mise_env_file.as_deref().expect("the repository scope has a fragment");
}

/// The fragment's text.
fn fragment(rig: &Rig) -> String {
    return fs::read_to_string(fragment_path(rig)).expect("the fragment exists");
}

/// The `[env]` body of a fragment:
/// every line after the table header.
fn env_body(text: &str) -> String {
    let (_header, body) = text.split_once("[env]\n").expect("the fragment has an [env] table");
    return body.to_string();
}

/// A rig whose rust tool has no environment and whose android tool exports `pairs`.
fn rig_exporting(pairs: &[(&str, &str)]) -> Rig {
    let mut rig = Rig::new();
    set_env(&mut rig, "rust", &[]);
    set_env(&mut rig, "android-sdk", pairs);
    return rig;
}

fn path_text(path: &Path) -> String {
    return path.to_str().expect("utf-8 path").to_string();
}

#[test]
fn the_repository_fragment_sits_in_the_mise_conf_d_directory_of_the_worktree_and_the_global_scope_has_none() {
    let rig = Rig::new();
    assert_eq!(rig.scope.mise_env_file, Some(rig.scope.root.join(".config/mise/conf.d/30-toolchain-env.local.toml")));
    let env = EnvMap::from_pairs(&[("HOME", "/home/someone"), ("XDG_CONFIG_HOME", "/config/home")]);
    let scope = global_scope(&env).expect("a global scope");
    assert_eq!(scope.mise_env_file, None);
}

#[test]
fn a_lock_entry_with_env_writes_absolute_values_under_the_toolchain_root_and_passes_literals_through() {
    let mut rig = Rig::new();
    set_env(&mut rig, "android-sdk", &[("ANDROID_HOME", "android-sdk/23.0"), ("ANDROID_SDK_ROOT", "android-sdk/23.0")]);
    let outcome = write_tool_env(&rig.context()).expect("the fragment is written");
    let sdk = path_text(&rig.scope.toolchain_root.join("android-sdk/23.0"));
    assert!(Path::new(&sdk).is_absolute(), "{sdk}");
    assert_eq!(outcome.file.as_deref(), Some(fragment_path(&rig)));
    assert_eq!(outcome.names, vec!["ANDROID_HOME", "ANDROID_SDK_ROOT", "RUSTUP_TOOLCHAIN"]);
    assert_eq!(
        env_body(&fragment(&rig)),
        format!("ANDROID_HOME = \"{sdk}\"\nANDROID_SDK_ROOT = \"{sdk}\"\nRUSTUP_TOOLCHAIN = \"nightly-2026-10-30\"\n")
    );
    assert!(fragment(&rig).starts_with("# Generated by mpm-shadow"), "the header says who writes it");
}

#[test]
fn a_plan_value_with_the_version_placeholder_reaches_the_fragment_as_an_absolute_version_expanded_path() {
    let mut rig = Rig::new();
    let java_plan = vec![("JAVA_HOME".to_string(), "java/{version}".to_string())];
    let mut declaration = rig.tool("android-sdk").declaration;
    declaration.env = java_plan;
    let expanded = expand_version(&declaration, "21.0.13+9.0.LTS");
    for tool in &mut rig.lock.tools {
        if tool.declaration.id == "android-sdk" {
            tool.declaration.env = expanded.env.clone();
        }
    }
    write_tool_env(&rig.context()).expect("the fragment is written");
    let java = path_text(&rig.scope.toolchain_root.join("java/21.0.13+9.0.LTS"));
    assert!(env_body(&fragment(&rig)).contains(&format!("JAVA_HOME = \"{java}\"\n")), "{}", fragment(&rig));
}

/// What:
/// Adds the `java` tool to the rig's lock the way the repository's plan declares it:
/// an archive of Adoptium's Temurin JDK whose `env` names its own directory,
/// the plan line `"JAVA_HOME": "java/{version}"` already expanded.
/// Why:
/// The value is the install directory,
/// while the archive unpacks the JDK into the release's own `jdk-<release>` folder inside it,
/// which is the layout `install` left on the machine (`.../java/temurin-21.0.13+9.0.LTS/jdk-21.0.13+9`).
fn add_java_tool(rig: &mut Rig) {
    let mut java = rig.tool("android-sdk");
    java.declaration.id = "java".to_string();
    java.declaration.request = Request::parse("java:temurin@21").expect("parses");
    java.declaration.bins = vec!["java".to_string(), "jar".to_string()];
    java.version = "temurin-21.0.13+9.0.LTS".to_string();
    java.declaration.env = vec![("JAVA_HOME".to_string(), format!("java/{}", java.version))];
    rig.lock.tools.push(java);
}

/// Writes the JDK an Adoptium archive unpacks into the tool's version directory:
/// its programs under `<version>/jdk-<release>/bin`,
/// and returns the JDK's home.
fn install_jdk(rig: &Rig, version: &str, release: &str) -> PathBuf {
    let home = rig.scope.toolchain_root.join("java").join(version).join(format!("jdk-{release}"));
    super::fakes::write_executable(&home.join("bin").join("java"));
    super::fakes::write_executable(&home.join("bin").join("jar"));
    return home;
}

/// What:
/// `JAVA_HOME` is exported as the directory the JDK was unpacked into,
/// not as the tool's version directory,
/// which holds nothing but that folder.
/// Why:
/// Gradle checks that `JAVA_HOME` names a directory holding `bin/java`,
/// `lib` and `conf`;
/// the fragment named `.../java/temurin-21.0.13+9.0.LTS`,
/// so `./gradlew --version` stopped with `ERROR: JAVA_HOME is set to an invalid directory`.
#[test]
fn a_tool_directory_that_holds_only_the_unpacked_jdk_exports_the_jdk_directory() {
    let mut rig = Rig::new();
    add_java_tool(&mut rig);
    let home = install_jdk(&rig, "temurin-21.0.13+9.0.LTS", "21.0.13+9");
    write_tool_env(&rig.context()).expect("the fragment is written");
    assert!(env_body(&fragment(&rig)).contains(&format!("JAVA_HOME = \"{}\"\n", path_text(&home))), "{}", fragment(&rig));
}

/// The control:
/// a directory that holds no unpacked folder,
/// or several,
/// is exported as it is named.
#[test]
fn a_tool_directory_that_is_the_home_itself_is_exported_as_it_is_named() {
    let mut rig = Rig::new();
    add_java_tool(&mut rig);
    let version_dir = rig.scope.toolchain_root.join("java").join("temurin-21.0.13+9.0.LTS");
    super::fakes::write_executable(&version_dir.join("bin").join("java"));
    super::fakes::write_executable(&version_dir.join("bin").join("jar"));
    write_tool_env(&rig.context()).expect("the fragment is written");
    assert!(
        env_body(&fragment(&rig)).contains(&format!("JAVA_HOME = \"{}\"\n", path_text(&version_dir))),
        "a JDK unpacked without its own folder stays where it is: {}",
        fragment(&rig)
    );
}

#[test]
fn a_tool_removed_from_the_lock_loses_its_variables_and_a_lock_without_env_removes_the_fragment() {
    let mut rig = rig_exporting(&[("ANDROID_HOME", "android-sdk/23.0")]);
    write_tool_env(&rig.context()).expect("the fragment is written");
    assert!(fragment(&rig).contains("ANDROID_HOME"));
    rig.lock.tools.retain(|tool| return tool.declaration.id != "android-sdk");
    set_env(&mut rig, "rust", &[("RUSTUP_TOOLCHAIN", "nightly-2026-10-30")]);
    let outcome = write_tool_env(&rig.context()).expect("the fragment is rewritten");
    assert_eq!(outcome.names, vec!["RUSTUP_TOOLCHAIN"]);
    assert!(!fragment(&rig).contains("ANDROID_HOME"), "{}", fragment(&rig));
    set_env(&mut rig, "rust", &[]);
    let emptied = write_tool_env(&rig.context()).expect("the fragment is removed");
    assert!(emptied.names.is_empty());
    assert!(!fragment_path(&rig).exists(), "no variables, no fragment");
    write_tool_env(&rig.context()).expect("removing an absent fragment is not an error");
}

#[test]
fn a_tool_that_does_not_apply_to_the_host_family_exports_nothing() {
    let mut rig = rig_exporting(&[("ANDROID_HOME", "android-sdk/23.0")]);
    for tool in &mut rig.lock.tools {
        if tool.declaration.id == "android-sdk" {
            tool.declaration.os = Some(vec![OsFamily::Macos]);
        }
    }
    rig.host = Host { platform: "linux-x64".to_string(), family: Some(OsFamily::Linux) };
    let outcome = write_tool_env(&rig.context()).expect("nothing to write");
    assert!(outcome.names.is_empty());
    assert!(!fragment_path(&rig).exists());
}

#[test]
fn quotes_and_backslashes_in_a_literal_are_encoded_so_the_toml_string_stays_closed() {
    let rig = rig_exporting(&[("NOTE", "say \"hi\" to a\\b")]);
    write_tool_env(&rig.context()).expect("quotes and backslashes are encodable");
    assert_eq!(env_body(&fragment(&rig)), "NOTE = \"say \\\"hi\\\" to a\\\\b\"\n");
}

/// Values mise would act on or a file could not hold:
/// each must be refused by name.
const REFUSED_VALUES: &[&str] = &[
    "android-sdk/../../etc",
    "../outside",
    "/etc/passwd",
    "android-sdk/./23.0",
    "tera/{{ env.SECRET }}",
    "{{ env.SECRET }}",
    "tag/{% include \"x\" %}",
    "comment/{# x #}",
    "brace/}",
    "home/$HOME",
    "$HOME",
    "line\nbreak",
    "tab\tin/value",
    "unexpanded/{version}",
];

#[test]
fn a_value_that_leaves_the_root_or_that_mise_would_template_or_expand_is_refused_naming_tool_and_variable() {
    let mut accepted: Vec<&str> = Vec::new();
    for value in REFUSED_VALUES.iter().copied() {
        let rig = rig_exporting(&[("ANDROID_HOME", value)]);
        match write_tool_env(&rig.context()) {
            Ok(_) => accepted.push(value),
            Err(error) => {
                assert_eq!(error.kind, ErrorKind::Failure, "{value}");
                assert!(error.message.contains("android-sdk") && error.message.contains("ANDROID_HOME"), "{value}: {error}");
                assert!(!fragment_path(&rig).exists(), "{value}: nothing may be written");
            }
        }
    }
    assert!(accepted.is_empty(), "values that were written instead of refused: {accepted:?}");
}

#[test]
fn a_relative_toolchain_root_cannot_make_a_value_absolute_and_is_refused() {
    let mut rig = rig_exporting(&[("ANDROID_HOME", "android-sdk/23.0")]);
    rig.scope.toolchain_root = std::path::PathBuf::from("relative/root");
    let error = write_tool_env(&rig.context()).expect_err("the root is relative");
    assert!(error.message.contains("not an absolute path"), "{error}");
}

#[test]
fn a_refused_value_leaves_the_fragment_of_the_last_good_run_in_place() {
    let mut rig = rig_exporting(&[("ANDROID_HOME", "android-sdk/23.0")]);
    write_tool_env(&rig.context()).expect("the fragment is written");
    let before = fragment(&rig);
    set_env(&mut rig, "android-sdk", &[("ANDROID_HOME", "{{ env.SECRET }}")]);
    write_tool_env(&rig.context()).expect_err("the value is refused");
    assert_eq!(fragment(&rig), before);
}

/// Names that are not a plain environment variable name:
/// each must be refused,
/// because a TOML bare key would end or split there.
const REFUSED_NAMES: &[&str] = &["", "1ST", "A B", "A=B", "A.B", "A\"B", "A\nB = \"x\""];

#[test]
fn a_variable_name_that_is_not_a_plain_identifier_is_refused() {
    let mut accepted: Vec<&str> = Vec::new();
    for name in REFUSED_NAMES.iter().copied() {
        let rig = rig_exporting(&[(name, "value")]);
        match write_tool_env(&rig.context()) {
            Ok(_) => accepted.push(name),
            Err(error) => {
                assert!(error.message.contains("android-sdk"), "{name:?}: {error}");
                assert!(!fragment_path(&rig).exists(), "{name:?}: nothing may be written");
            }
        }
    }
    assert!(accepted.is_empty(), "names that were written instead of refused: {accepted:?}");
}

#[test]
fn two_tools_that_export_one_name_with_different_values_are_refused_and_equal_values_are_fine() {
    let mut rig = Rig::new();
    set_env(&mut rig, "android-sdk", &[("RUSTUP_TOOLCHAIN", "other-channel")]);
    let error = write_tool_env(&rig.context()).expect_err("the two tools disagree");
    assert!(error.message.contains("rust") && error.message.contains("android-sdk"), "{error}");
    set_env(&mut rig, "android-sdk", &[("RUSTUP_TOOLCHAIN", "nightly-2026-10-30")]);
    let outcome = write_tool_env(&rig.context()).expect("equal values agree");
    assert_eq!(outcome.names, vec!["RUSTUP_TOOLCHAIN"]);
}

#[test]
fn install_writes_the_fragment_from_the_whole_lock_and_a_partial_sync_leaves_it_alone() {
    let mut rig = Rig::new();
    set_env(&mut rig, "android-sdk", &[("ANDROID_HOME", "android-sdk/23.0")]);
    let report = sync_tools(&rig.context(), Some(&["node".to_string()]));
    assert!(report.failed.iter().all(|(id, _)| return id != "tool environment"), "{:?}", report.failed);
    assert!(!fragment_path(&rig).exists(), "update's partial sync must not touch the fragment");
    sync_tools(&rig.context(), None);
    assert!(fragment(&rig).contains("ANDROID_HOME"), "{}", fragment(&rig));
    assert!(fragment(&rig).contains("RUSTUP_TOOLCHAIN"), "{}", fragment(&rig));
}

#[test]
fn install_reports_a_refused_value_as_a_failure_of_the_tool_environment() {
    let mut rig = Rig::new();
    set_env(&mut rig, "android-sdk", &[("ANDROID_HOME", "{{ env.SECRET }}")]);
    let report = sync_tools(&rig.context(), None);
    let failure = report.failed.iter().find(|(id, _)| return id == "tool environment").expect("the refusal is reported");
    assert!(failure.1.contains("ANDROID_HOME"), "{}", failure.1);
}

#[test]
fn a_global_install_writes_no_tool_environment_fragment_because_tool_variables_are_for_the_repository_only() {
    let mut rig = Rig::new();
    set_env(&mut rig, "android-sdk", &[("ANDROID_HOME", "android-sdk/23.0")]);
    rig.scope = global_scope(&rig.env).expect("a global scope");
    let config_home = rig.scope.home.join(".config");
    sync_tools(&rig.context(), None);
    let outcome = write_tool_env(&rig.context()).expect("a global scope has nothing to write");
    assert!(outcome.names.is_empty(), "{outcome:?}");
    assert!(!config_home.join("mise/conf.d/30-toolchain-env.toml").exists(), "no machine-wide fragment");
    assert!(!config_home.join("mise").exists(), "the global mise config directory is not even created");
}
