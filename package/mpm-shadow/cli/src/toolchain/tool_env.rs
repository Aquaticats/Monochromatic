//! What:
//! The tool environment:
//! the variables the lock's `env` blocks declare (`ANDROID_HOME`,
//! `JAVA_HOME`,
//! `RUSTUP_TOOLCHAIN`),
//! written as a generated mise
//!           configuration fragment.
//! Why:
//! Mise runs every task and shell of the repository (and, for the machine-global scope,
//! of the machine),
//! and reads every file of a `conf.d` directory in name order,
//! so a fragment there reaches them all with no committed line
//!           pointing at it.
//!
//! In TS you'd write (pseudocode):
//! ```ts
//! // tool-env.ts
//! export function writeToolEnv(ctx: Context): { file: string; names: string[] }  // throws on a value mise would misread
//! ```

/// Imports `BTreeMap`,
/// a map sorted by key,
/// from `std::collections`.
use std::collections::BTreeMap;
/// Imports `fs` from `std`.
use std::fs;
/// Imports `PathBuf` from `std::path`.
use std::path::PathBuf;

/// Imports `Context` from `super::context`.
use super::context::Context;
/// Imports `ToolchainError` from `super::error`.
use super::error::ToolchainError;
/// Imports `applies_to_family` from `super::layout`.
use super::layout::applies_to_family;

/// The comment that opens every generated fragment.
pub const FRAGMENT_HEADER: &str = "# Generated by mpm-shadow from the tool `env` blocks of toolchain.lock.json on every `install`; do not edit.\n\
# Mise reads every file of this directory in name order. A tool removed from the lock loses its variables here.\n";

/// What:
/// What `write_tool_env` did:
/// the fragment's path and the variable names it now holds.
/// Why:
/// The caller reports the names and tests assert them.
///
/// In TS you'd write (pseudocode):
/// ```ts
/// type ToolEnvOutcome = { file: string; names: string[] };
/// ```
#[derive(Clone, Debug, Default, Eq, PartialEq)]
pub struct ToolEnvOutcome {
    /// The fragment the variables are in (or were removed from).
    pub file: PathBuf,
    /// The variable names the fragment now holds,
    /// sorted.
    pub names: Vec<String>,
}

/// What:
/// A value of a lock's `env` block as the process sees it:
/// a value with a `/` is relative to the toolchain root and becomes absolute,
/// any other value is a literal.
/// Why:
/// The plan writes `android-sdk/{version}` so no machine path is committed;
/// `RUSTUP_TOOLCHAIN` is a channel name, not a path.
///
/// In TS you'd write (pseudocode):
/// ```ts
/// function resolveValue(toolchainRoot: string, value: string): string
/// ```
fn resolve_value(toolchain_root: &std::path::Path, value: &str) -> String {
    if value.contains('/') {
        return toolchain_root.join(value).to_string_lossy().to_string();
    }
    return value.to_string();
}

/// The TOML basic string for `value`:
/// quotes and backslashes escaped.
pub fn toml_string(value: &str) -> String {
    let mut text: String = String::from("\"");
    for character in value.chars() {
        if character == '"' || character == '\\' {
            text.push('\\');
        }
        text.push(character);
    }
    text.push('"');
    return text;
}

/// What:
/// The fragment's text for `variables`:
/// the header,
/// the `[env]` table and one `NAME = "value"` line per variable,
/// in name order.
/// Why:
/// Mise reads the `[env]` table of every `conf.d` file;
/// name order keeps the file stable between runs.
///
/// In TS you'd write (pseudocode):
/// ```ts
/// export function renderFragment(variables: Map<string, string>): string
/// ```
pub fn render_fragment(variables: &BTreeMap<String, String>) -> String {
    let mut text: String = String::from(FRAGMENT_HEADER);
    text.push_str("[env]\n");
    for (name, value) in variables {
        text.push_str(&format!("{name} = {}\n", toml_string(value)));
    }
    return text;
}

/// What:
/// Writes the scope's tool environment fragment from the lock:
/// every `env` variable of every tool that applies to this host,
/// or no file when there are none.
/// Why:
/// The fragment is rewritten whole from the lock on every `install`,
/// so a tool removed from the lock loses its variables
/// and nothing is hand-maintained.
///
/// In TS you'd write (pseudocode):
/// ```ts
/// export function writeToolEnv(ctx: Context): ToolEnvOutcome  // throws
/// ```
pub fn write_tool_env(ctx: &Context) -> Result<ToolEnvOutcome, ToolchainError> {
    let mut variables: BTreeMap<String, String> = BTreeMap::new();
    for tool in ctx.tools {
        if !applies_to_family(&tool.declaration.os, ctx.host.family) {
            continue;
        }
        for (name, value) in &tool.declaration.env {
            variables.insert(name.clone(), resolve_value(&ctx.scope.toolchain_root, value));
        }
    }
    let file: PathBuf = ctx.scope.mise_env_file.clone();
    let names: Vec<String> = variables.keys().cloned().collect();
    if variables.is_empty() {
        match fs::remove_file(&file) {
            Ok(()) => {}
            Err(error) if error.kind() == std::io::ErrorKind::NotFound => {}
            Err(error) => {
                return Err(ToolchainError::failure(format!("cannot remove {}: {error}", file.display())));
            }
        }
        return Ok(ToolEnvOutcome { file, names });
    }
    let text: String = render_fragment(&variables);
    if fs::read_to_string(&file).ok().as_deref() == Some(text.as_str()) {
        return Ok(ToolEnvOutcome { file, names });
    }
    if let Some(parent) = file.parent()
        && let Err(error) = fs::create_dir_all(parent)
    {
        return Err(ToolchainError::failure(format!("cannot create {}: {error}", parent.display())));
    }
    // A name mise skips (it ignores files starting with a dot), so a killed run leaves nothing it would load.
    let mut temporary_name = std::ffi::OsString::from(".");
    temporary_name.push(file.file_name().unwrap_or_default());
    temporary_name.push(format!(".{}.tmp", std::process::id()));
    let temporary: PathBuf = file.with_file_name(temporary_name);
    if let Err(error) = fs::write(&temporary, &text) {
        return Err(ToolchainError::failure(format!("cannot write {}: {error}", temporary.display())));
    }
    if let Err(error) = fs::rename(&temporary, &file) {
        // Best effort: the temporary file is useless once the rename failed.
        let _ = fs::remove_file(&temporary);
        return Err(ToolchainError::failure(format!("cannot place {}: {error}", file.display())));
    }
    return Ok(ToolEnvOutcome { file, names });
}
