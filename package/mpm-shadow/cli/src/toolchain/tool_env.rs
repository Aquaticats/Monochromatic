//! What:
//! The tool environment:
//! the variables the lock's `env` blocks declare (`ANDROID_HOME`,
//! `JAVA_HOME`,
//! `RUSTUP_TOOLCHAIN`),
//! written as a generated mise
//!           configuration fragment.
//! Why:
//! Mise runs every task and shell of the repository,
//! and reads every file of a `conf.d` directory in name order,
//! so a fragment there reaches them all with no committed line
//!           pointing at it.
//! Only the repository scope has a fragment:
//! the machine-global scope exports nothing,
//! so no tool variable reaches a shell outside the repository.
//!
//! In TS you'd write (pseudocode):
//! ```ts
//! // tool-env.ts
//! export function writeToolEnv(ctx: Context): { file: string; names: string[] }  // throws on a value mise would misread
//! ```

/// Imports `BTreeMap`,
/// a map sorted by key,
/// from `std::collections`.
use std::collections::BTreeMap;
/// Imports `fs` from `std`.
use std::fs;
/// Imports `PathBuf` from `std::path`.
use std::path::{Path, PathBuf};

/// Imports `Context` from `super::context`.
use super::context::Context;
/// Imports `ToolchainError` from `super::error`.
use super::error::ToolchainError;
/// Imports `applies_to_family` from `super::layout`.
use super::layout::applies_to_family;

/// The comment that opens every generated fragment.
pub const FRAGMENT_HEADER: &str = "# Generated by mpm-shadow from the tool `env` blocks of toolchain.lock.json on every `install`; do not edit.\n\
# Mise reads every file of this directory in name order. A tool removed from the lock loses its variables here.\n";

/// What:
/// What `write_tool_env` did:
/// the fragment's path and the variable names it now holds.
/// Why:
/// The caller reports the names and tests assert them.
///
/// In TS you'd write (pseudocode):
/// ```ts
/// type ToolEnvOutcome = { file: string; names: string[] };
/// ```
#[derive(Clone, Debug, Default, Eq, PartialEq)]
pub struct ToolEnvOutcome {
    /// The fragment the variables are in (or were removed from);
    /// `None` for a scope that has no fragment (the machine-global one).
    pub file: Option<PathBuf>,
    /// The variable names the fragment now holds,
    /// sorted.
    pub names: Vec<String>,
}

/// What:
/// The refusal for one variable of one tool:
/// names the tool and variable,
/// the value,
/// why it is refused and what to change.
/// Why:
/// The person reading it has only this line:
/// a refused value stops the fragment from being written,
/// so the message must say that and where to fix it.
///
/// In TS you'd write (pseudocode):
/// ```ts
/// function refusal(toolId: string, name: string, value: string, reason: string): Error
/// ```
fn refusal(tool_id: &str, name: &str, value: &str, reason: &str) -> ToolchainError {
    return ToolchainError::failure(format!(
        "tool `{tool_id}` declares the environment variable `{name}` = {value:?}, which cannot be exported to mise: {reason}. \
         The generated mise fragment was not rewritten (an earlier one stays as it was); fix the `env` block of `{tool_id}` in \
         toolchain.plan.jsonc, run `mpm-shadow install --lockfile-only`, then `mpm-shadow install` again"
    ));
}

/// Whether a character after the first may appear in an environment variable name.
fn is_name_character(character: char) -> bool {
    return character.is_ascii_alphanumeric() || character == '_';
}

/// What:
/// Whether `name` is a plain environment variable name:
/// an ASCII letter or underscore,
/// then ASCII letters,
/// digits or underscores.
/// Why:
/// The name is written as a TOML bare key;
/// anything else could end the key,
/// start a new line or a table.
///
/// In TS you'd write (pseudocode):
/// ```ts
/// function isPlainName(name: string): boolean  // /^[A-Za-z_][A-Za-z0-9_]*$/
/// ```
fn is_plain_name(name: &str) -> bool {
    let mut characters = name.chars();
    let Some(first) = characters.next() else {
        return false;
    };
    if !(first.is_ascii_alphabetic() || first == '_') {
        return false;
    }
    return characters.all(is_name_character);
}

/// What:
/// Checks that a relative value stays below the toolchain root:
/// every `/`-separated segment is a real name,
/// never empty (a leading `/` makes an absolute path that replaces the root),
/// `.` or `..`.
/// Why:
/// `Path::join` with an absolute value discards the root,
/// and `..` climbs out of it;
/// the person asked for a path inside the toolchain root and no more.
///
/// In TS you'd write (pseudocode):
/// ```ts
/// function staysInside(value: string): boolean  // value.split('/').every(s => s !== '' && s !== '.' && s !== '..')
/// ```
fn stays_inside_root(value: &str) -> bool {
    for segment in value.split('/') {
        if segment.is_empty() || segment == "." || segment == ".." {
            return false;
        }
    }
    return true;
}

/// What:
/// The characters mise would act on or a line could not hold:
/// the first one in `text`,
/// with the reason.
/// Why:
/// Mise reads every value as a Tera template (`{{ }}`,
/// `{% %}`,
/// `{# #}`) and expands `$NAME`;
/// a control character (a newline above all) ends the TOML line.
/// The lock has no value that needs any of them,
/// so refusing is safer than escaping a dialect this program does not own.
///
/// In TS you'd write (pseudocode):
/// ```ts
/// function unsafeCharacter(text: string): string | undefined
/// ```
fn unsafe_character(text: &str) -> Option<&'static str> {
    for character in text.chars() {
        if character.is_control() {
            return Some("it contains a control character (a newline or tab would end the TOML line)");
        }
        if character == '{' || character == '}' {
            return Some("it contains a brace, which mise reads as the start of a template (`{{ }}`, `{% %}`, `{# #}`)");
        }
        if character == '$' {
            return Some("it contains `$`, which mise expands as an environment variable");
        }
    }
    return None;
}

/// What:
/// A value of a lock's `env` block as the process sees it:
/// a value with a `/` is relative to the toolchain root and becomes absolute,
/// any other value is a literal.
/// Why:
/// The plan writes `android-sdk/{version}` so no machine path is committed;
/// `RUSTUP_TOOLCHAIN` is a channel name,
/// not a path.
/// Refused when the name or value would be misread (see the checks above).
///
/// In TS you'd write (pseudocode):
/// ```ts
/// function resolveValue(toolchainRoot: string, toolId: string, name: string, value: string): string  // throws
/// ```
fn resolve_value(toolchain_root: &Path, tool_id: &str, name: &str, value: &str) -> Result<String, ToolchainError> {
    if !is_plain_name(name) {
        return Err(refusal(tool_id, name, value, "the name is not a plain identifier (ASCII letters, digits and underscores, not starting with a digit)"));
    }
    let mut resolved: String = value.to_string();
    if value.contains('/') {
        if !stays_inside_root(value) {
            return Err(refusal(
                tool_id,
                name,
                value,
                "a value with `/` is relative to the toolchain root and must not be absolute, empty-segmented, or contain `.` or `..`",
            ));
        }
        if !toolchain_root.is_absolute() {
            return Err(refusal(
                tool_id,
                name,
                value,
                &format!("the toolchain root {} is not an absolute path, so the value cannot be made absolute", toolchain_root.display()),
            ));
        }
        resolved = toolchain_root.join(value).to_string_lossy().to_string();
    }
    if let Some(reason) = unsafe_character(&resolved) {
        return Err(refusal(tool_id, name, &resolved, reason));
    }
    return Ok(resolved);
}

/// The TOML basic string for `value`:
/// quotes and backslashes escaped.
pub fn toml_string(value: &str) -> String {
    let mut text: String = String::from("\"");
    for character in value.chars() {
        if character == '"' || character == '\\' {
            text.push('\\');
        }
        text.push(character);
    }
    text.push('"');
    return text;
}

/// What:
/// The fragment's text for `variables`:
/// the header,
/// the `[env]` table and one `NAME = "value"` line per variable,
/// in name order.
/// Why:
/// Mise reads the `[env]` table of every `conf.d` file;
/// name order keeps the file stable between runs.
///
/// In TS you'd write (pseudocode):
/// ```ts
/// export function renderFragment(variables: Map<string, string>): string
/// ```
pub fn render_fragment(variables: &BTreeMap<String, String>) -> String {
    let mut text: String = String::from(FRAGMENT_HEADER);
    text.push_str("[env]\n");
    for (name, value) in variables {
        text.push_str(&format!("{name} = {}\n", toml_string(value)));
    }
    return text;
}

/// What:
/// Writes the repository scope's tool environment fragment from the lock
/// (the machine-global scope has none and nothing happens):
/// every `env` variable of every tool that applies to this host,
/// or no file when there are none.
/// Why:
/// The fragment is rewritten whole from the lock on every `install`,
/// so a tool removed from the lock loses its variables
/// and nothing is hand-maintained.
///
/// In TS you'd write (pseudocode):
/// ```ts
/// export function writeToolEnv(ctx: Context): ToolEnvOutcome  // throws
/// ```
pub fn write_tool_env(ctx: &Context) -> Result<ToolEnvOutcome, ToolchainError> {
    let Some(file) = ctx.scope.mise_env_file.clone() else {
        return Ok(ToolEnvOutcome::default());
    };
    let mut variables: BTreeMap<String, String> = BTreeMap::new();
    // Which tool declared each name first, so a second tool with another value is named in the refusal.
    let mut owners: BTreeMap<String, String> = BTreeMap::new();
    for tool in ctx.tools {
        if !applies_to_family(&tool.declaration.os, ctx.host.family) {
            continue;
        }
        let tool_id: &str = &tool.declaration.id;
        for (name, value) in &tool.declaration.env {
            let resolved: String = resolve_value(&ctx.scope.toolchain_root, tool_id, name, value)?;
            if let Some(existing) = variables.get(name)
                && *existing != resolved
            {
                let owner: &str = owners.get(name).map(String::as_str).unwrap_or("another tool");
                return Err(refusal(
                    tool_id,
                    name,
                    &resolved,
                    &format!("tool `{owner}` already declares it as {existing:?}, and one name cannot hold two values"),
                ));
            }
            owners.insert(name.clone(), tool_id.to_string());
            variables.insert(name.clone(), resolved);
        }
    }
    let names: Vec<String> = variables.keys().cloned().collect();
    if variables.is_empty() {
        match fs::remove_file(&file) {
            Ok(()) => {}
            Err(error) if error.kind() == std::io::ErrorKind::NotFound => {}
            Err(error) => {
                return Err(ToolchainError::failure(format!("cannot remove {}: {error}", file.display())));
            }
        }
        return Ok(ToolEnvOutcome { file: Some(file), names });
    }
    let text: String = render_fragment(&variables);
    if fs::read_to_string(&file).ok().as_deref() == Some(text.as_str()) {
        return Ok(ToolEnvOutcome { file: Some(file), names });
    }
    if let Some(parent) = file.parent()
        && let Err(error) = fs::create_dir_all(parent)
    {
        return Err(ToolchainError::failure(format!("cannot create {}: {error}", parent.display())));
    }
    // A name mise skips (it ignores files starting with a dot), so a killed run leaves nothing it would load.
    let mut temporary_name = std::ffi::OsString::from(".");
    temporary_name.push(file.file_name().unwrap_or_default());
    temporary_name.push(format!(".{}.tmp", std::process::id()));
    let temporary: PathBuf = file.with_file_name(temporary_name);
    if let Err(error) = fs::write(&temporary, &text) {
        return Err(ToolchainError::failure(format!("cannot write {}: {error}", temporary.display())));
    }
    if let Err(error) = fs::rename(&temporary, &file) {
        // Best effort: the temporary file is useless once the rename failed.
        let _ = fs::remove_file(&temporary);
        return Err(ToolchainError::failure(format!("cannot place {}: {error}", file.display())));
    }
    return Ok(ToolEnvOutcome { file: Some(file), names });
}
