//! What:     TOML text for catalog-owned values, and the `toml_edit` values parsed from that text.
//! Why:      Entries are rendered by hand (always double-quoted strings, fixed field order) and then parsed, so the
//!           document keeps exactly the bytes the TypeScript tool wrote instead of whatever quoting `toml_edit`
//!           would pick for a freshly built value.
//!
//! In TS you'd write (pseudocode):
//! ```ts
//! // render.ts
//! export function renderGeneratedValue(generated: GeneratedEntry): string
//! export function renderEntryValue(entry: RustCatalogEntry): string
//! ```

use toml_edit::Value;

use crate::quote::quote;
use crate::site::GeneratedEntry;
use crate::types::Entry;

/// Comment above each crate's generated `[workspace.dependencies]` table.
pub const GENERATED_TABLE_COMMENT: &str =
    "# Generated by file-enforcer from rust-catalog.toml; edit the catalog, not this table (doc/decision/rust-dependency-catalog.md).";

/// What:     `pub fn render_generated_value(generated: &GeneratedEntry) -> String` renders one generated
///           `[workspace.dependencies]` value: a plain string only for a registry entry without a rename that keeps
///           default features, otherwise an inline table with `version` or `git` + `rev`, then `package`, then
///           `default-features = false`.
/// Why:      The field order is fixed so the same inputs always render the same bytes.
///
/// In TS you'd write (pseudocode):
/// ```ts
/// export function renderGeneratedValue(generated: GeneratedEntry): string
/// ```
pub fn render_generated_value(generated: &GeneratedEntry) -> String {
    let mut tail: Vec<String> = Vec::new();
    if let Some(package) = generated.entry.package() {
        tail.push(format!("package = {}", quote(package)));
    }
    if !generated.default_features {
        tail.push("default-features = false".to_string());
    }
    let mut fields: Vec<String> = Vec::new();
    match &generated.entry {
        Entry::Git { git, rev, .. } => {
            fields.push(format!("git = {}", quote(git)));
            fields.push(format!("rev = {}", quote(rev)));
        }
        Entry::Registry { version, .. } => {
            if tail.is_empty() {
                return quote(version);
            }
            fields.push(format!("version = {}", quote(version)));
        }
    }
    fields.extend(tail);
    return format!("{{ {} }}", fields.join(", "));
}

/// Renders a catalog entry as the value the catalog file itself holds (default features kept).
pub fn render_entry_value(entry: &Entry) -> String {
    return render_generated_value(&GeneratedEntry {
        entry: entry.clone(),
        default_features: true,
    });
}

/// What:     `pub fn parse_value(text: &str) -> Value` parses rendered value text into a `toml_edit::Value` that
///           keeps that text verbatim when printed.
/// Why:      The text always comes from this module's renderers, so a parse failure is a bug in them; it is reported
///           by panicking with the text rather than hidden.
///
/// In TS you'd write (pseudocode):
/// ```ts
/// function parseValue(text: string): Value { return parseTomlValue(text); } // throws on a renderer bug
/// ```
pub fn parse_value(text: &str) -> Value {
    match text.parse::<Value>() {
        Ok(value) => return value,
        Err(error) => panic!("internal error: rendered TOML value {text} did not parse: {error}"),
    }
}
