// THE CAPITALISED ENGLISH WORDS THAT STAND BESIDE A NAME WITHOUT BEING PART OF
// IT, for the whole-name arrival check (`whole-name-arrival.ts`).
//
// WHY A LIST AND NOT A TEST. A capitalised word beside a declared form is
// either the start of a sentence, a title, or a piece of a name the front
// matter never declared (`Xing` beside `Lili`, the fusion that shipped a
// renamed person from XingZ60 slice 80). The two cannot be told apart by
// shape, and no word list of the language is in this repository, so the words
// that are known not to be name pieces are named here and every other
// capitalised word blocks. A word missing from the list costs a refused swap,
// which is what the floor did before swaps were met at all; a name piece
// wrongly on it costs a renamed person, so the list holds no word that is also
// a romanised Chinese or Japanese syllable (`Long`, `Sun`, `Man`, `Ran`, `He`, `She`,
// `Can`, `An`, `Ah` stay off, and neither article is on it).
//
// DRAWN FROM A CENSUS, then completed with the same families. Measured
// 2026-10-20 over the 91 pinned archives and 281 settled pages with a declared
// form: 7,596 whole-name occurrences, of which 647 sides had a capitalised
// neighbour, and the words in the set cover the sentence openers, titles and kin
// words among them (`When` 87, `But` 69, `After` 45, `Although` 31, `Was` 30,
// `As` 26, `Perhaps` 24, `Sister` 23, `And` 23, `In` 21, `For` 21, `The` 18).

