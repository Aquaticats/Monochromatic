import { createHash, } from 'node:crypto';
import {
  readFile,
  writeFile,
} from 'node:fs/promises';
import { join, } from 'node:path';

import {
  type CodeRange,
  type EastAsianWidthTable,
  parseEastAsianWidth,
  textOfRange,
} from './east-asian-width-parse.test-fixture.ts';

//region East Asian Width generator
// THE TABLE OF `east-asian-width-table.test-fixture.ts` IS WRITTEN HERE FROM UNICODE'S DATA FILE (ledger B1413). Run
// `EAST_ASIAN_WIDTH_FILE=<path of EastAsianWidth.txt> mise run //package/translation-repair/source-scan:generate:east-asian-width`
// over the file of the Unicode version the tree's node reports (`process.versions.unicode`), downloaded into a folder of
// its own and read as data. The table names the version, the address of the file and the file's SHA-256, so a reader can
// fetch the same file and run this again.

/**
 Address of the file for a version, from which the table was made.

 @param version - Unicode version, such as `17.0.0`

 @returns Address on the Unicode site

 @example
 ```ts
 const address = sourceAddressOf({ version: '17.0.0', },);
 ```
 */
export function sourceAddressOf({ version, }: { readonly version: string; },): string {
  return `https://www.unicode.org/Public/${version}/ucd/EastAsianWidth.txt`;
}

/**
 Most characters a line of the table holds, so every line fits the width the repository sets for source.
 */
export const LINE_LIMIT = 100;

/**
 Packs ranges into lines of at most the limit, separated by spaces.

 @param ranges - ranges in order

 @returns Lines, each a text `rangesOfLines` reads back

 @example
 ```ts
 const lines = linesOfRanges({ ranges, },);
 ```
 */
export function linesOfRanges({ ranges, }: { readonly ranges: readonly CodeRange[]; },): readonly string[] {
  /**
   Lines closed so far.
   */
  const lines: string[] = [];
  /**
   The line being filled.
   */
  let current = '';
  for (const range of ranges) {
    /**
     The range as text.
     */
    const word = textOfRange({ range, },);
    if ((current !== '') && ((current.length + 1
      + word.length) > LINE_LIMIT)) {
      lines.push(current,);
      current = '';
    }
    current = (current === '') ? word : `${current} ${word}`;
  }
  if (current !== '')
    lines.push(current,);
  return lines;
}

/**
 Writes the lines of a constant as quoted strings, one to a line.

 @param name - name of the exported constant

 @param lines - its lines

 @returns Source text of the declaration

 @example
 ```ts
 const source = declarationOf({ name: 'WIDE_RANGE_LINES', lines: ['2329-232A',], },);
 ```
 */
function declarationOf(
  {
    name,
    lines,
  }: {
    readonly name: string;
    readonly lines: readonly string[];
  },
): string {
  return [
    `export const ${name}: readonly string[] = [`,
    ...lines.map(function quoted(line,): string {
      return `  '${line}',`;
    },),
    '];',
  ].join('\n',);
}

/**
 Source text of the generated table module.

 @param table - what the file gave

 @param sha256 - SHA-256 of the file, in hexadecimal

 @returns Module text

 @example
 ```ts
 const source = tableSourceOf({ table, sha256, },);
 ```
 */
export function tableSourceOf(
  {
    table,
    sha256,
  }: {
    readonly table: EastAsianWidthTable;
    readonly sha256: string;
  },
): string {
  return [
    '//region East Asian Width table',
    '// GENERATED BY `east-asian-width-generate.test-fixture.ts`; do not edit it by hand (ledger B1413).',
    `// Source: ${sourceAddressOf({ version: table.version, },)}`,
    `// Unicode version ${table.version}, the version the tree's node reports in \`process.versions.unicode\`.`,
    `// SHA-256 of the file: ${sha256}`,
    '// Each line holds ranges of code points as first-last in hexadecimal, separated by spaces.',
    '',
    '/**',
    ' Unicode version of the data file the table was made from.',
    ' */',
    `export const EAST_ASIAN_WIDTH_VERSION = '${table.version}';`,
    '',
    '/**',
    ' SHA-256 of that file, in hexadecimal.',
    ' */',
    `export const EAST_ASIAN_WIDTH_SHA256 = '${sha256}';`,
    '',
    '/**',
    ' Code points of East_Asian_Width W or F, which fill two columns, with the defaults the header of the file states.',
    ' */',
    declarationOf({
      name: 'WIDE_RANGE_LINES',
      lines: linesOfRanges({ ranges: table.wide, },),
    },),
    '',
    '/**',
    ' Code points whose General_Category is a mark (Mn, Mc, Me), which fill no column of their own.',
    ' */',
    declarationOf({
      name: 'MARK_RANGE_LINES',
      lines: linesOfRanges({ ranges: table.marks, },),
    },),
    '',
    '//endregion East Asian Width table',
    '',
  ].join('\n',);
}

/**
 Path of the generated table module, beside this generator.
 */
export const TABLE_PATH = join(
  import.meta.dirname,
  'east-asian-width-table.test-fixture.ts',
);

/**
 Reads the data file and writes the generated table module.

 @param dataPath - path of the downloaded `EastAsianWidth.txt`

 @param tablePath - path to write the module to, `TABLE_PATH` for the tree's table

 @returns Version of the table written

 @throws {@link Error} when the file is not `EastAsianWidth.txt`

 @example
 ```ts
 const version = await generateTable({ dataPath: 'EastAsianWidth.txt', tablePath: TABLE_PATH, },);
 ```
 */
export async function generateTable(
  {
    dataPath,
    tablePath,
  }: {
    readonly dataPath: string;
    readonly tablePath: string;
  },
): Promise<string> {
  /**
   Bytes of the file, which the hash is taken over.
   */
  const bytes = await readFile(dataPath,);
  /**
   What the file gave.
   */
  const table = parseEastAsianWidth({ text: bytes.toString('utf8',), },);
  await writeFile(
    tablePath,
    tableSourceOf({
      table,
      sha256: createHash('sha256',)
        .update(bytes,)
        .digest('hex',),
    },),
  );
  return table.version;
}

